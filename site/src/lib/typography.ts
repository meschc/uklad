/**
 * Запрет висячих строк — та же половина правила, что в `src/lib/i18n.ts`
 * редактора: короткое слово или число не остаётся в конце строки, а
 * приклеивается к следующему слову неразрывным пробелом. Вторую половину
 * (балансировку последней строки) делает CSS в `index.css`.
 *
 * Функция скопирована, а не импортирована: `i18n.ts` тянет за собой стор и
 * типы редактора, а витрине нужен один разбор строки без всего приложения.
 */
const NBSP = " ";
const ORPHAN_RE = /(^|[\s(«"„])(\p{L}{1,2}|\d+)[ \t]+/gu;

export function noOrphans(s: string): string {
  if (!s.includes(" ")) return s;
  // Два прохода: цепочку коротких слов («и в углу») первый проход съедает
  // вместе с разделителем, на котором должен был сработать второй.
  return s.replace(ORPHAN_RE, `$1$2${NBSP}`).replace(ORPHAN_RE, `$1$2${NBSP}`);
}
