#!/bin/sh
# Старые куски сборки живут ещё KEEP_DAYS дней после выкладки.
#
# Экраны кабинета — отдельные файлы с хэшем в имени (`/assets/*`). Новая
# выкладка приносит новые имена, а вкладка, открытая до неё, просит старые —
# и без них падала «Importing a module script failed» (Кирилл 18.11). Поэтому
# файлы прошлых сборок копятся в томе `/keep` и подкладываются к новой
# сборке, пока им нет KEEP_DAYS дней. Новые файлы сборки ничем не
# перезаписываются: `cp -n` — только недостающие.
set -eu

KEEP=/keep/assets
DAYS="${KEEP_DAYS:-14}"
mkdir -p "$KEEP"
# 1. Устаревшее — вон: по времени последней выкладки, где файл ещё был.
find "$KEEP" -type f -mtime +"$DAYS" -delete
# 2. Прошлые сборки — к нынешней, не трогая её файлы.
cp -n "$KEEP"/* /srv/assets/ 2>/dev/null || true
# 3. Нынешняя сборка — в запас; копия обновляет время, срок идёт заново.
cp -f /srv/assets/* "$KEEP"/

exec caddy run --config /etc/caddy/Caddyfile --adapter caddyfile
