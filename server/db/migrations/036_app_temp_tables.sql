-- Роль приложения вправе заводить временные таблицы.
--
-- Нашли 14.11 при живой проверке стола (#154): `init.sql` отнимает у PUBLIC
-- все права на базу (`REVOKE ALL ON DATABASE uklad FROM PUBLIC`), а
-- `uklad.save_products` (013) складывает карточки во временную таблицу. На
-- базе, поднятой по инструкции развёртывания, кабинет с товарами не
-- сохранялся: 500 «permission denied to create temporary tables». Тесты этого
-- не видели — их база создавалась без `init.sql`, с правами PUBLIC по
-- умолчанию (теперь стенд отнимает их так же, как бой).
--
-- `init.sql` выполняется один раз, при первом запуске базы, поэтому уже
-- поднятому серверу право выдаёт эта миграция. Базу её владелец (под ним идут
-- миграции) вправе открыть роли приложения. Имя базы — текущее: в тестах оно
-- своё на прогон.

DO $$
BEGIN
  EXECUTE format('GRANT TEMPORARY ON DATABASE %I TO uklad_app', current_database());
END $$;
