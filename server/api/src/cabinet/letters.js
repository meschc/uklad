/**
 * Письма входа в кабинет: код подтверждения, код сброса и «вы уже с нами».
 *
 * Последнее — ответ на регистрацию с занятой почтой. Сайт в этом случае
 * говорит то же, что и всем («код отправлен»), а правду узнаёт только
 * владелец почты.
 */
/* global module */

const tail =
  "\n\nЕсли это были не вы, просто не отвечайте на письмо — без кода ничего не изменится.\n";

function codeLetter(purpose, code) {
  if (purpose === "reset") {
    return {
      subject: `${code} — код для нового пароля в Укладе`,
      text: `Здравствуйте!\n\nКод для нового пароля: ${code}\n\nОн действует 15 минут.` + tail,
    };
  }
  return {
    subject: `${code} — код подтверждения почты в Укладе`,
    text: `Здравствуйте!\n\nКод подтверждения почты: ${code}\n\nОн действует 15 минут.` + tail,
  };
}

function alreadyLetter(publicUrl) {
  return {
    subject: "Вы уже зарегистрированы в Укладе",
    text:
      `Здравствуйте!\n\nНа эту почту только что пытались зарегистрироваться, ` +
      `но кабинет с ней уже есть. Войти: ${publicUrl}/app/\n\n` +
      `Забыли пароль — на странице входа нажмите «Забыли пароль?», код придёт сюда.` +
      tail,
  };
}

/** Удаление назначено: когда, что пропадёт и как передумать. */
function deletionLetter(at, publicUrl) {
  const date = at.toLocaleDateString("ru-RU", {
    day: "numeric",
    month: "long",
    year: "numeric",
    timeZone: "Europe/Moscow",
  });
  return {
    subject: "Аккаунт в Укладе будет удалён",
    text:
      `Здравствуйте!\n\nВы попросили удалить аккаунт. Мы удалим его ${date}: ` +
      `почту, пароль, имя и фото, а если в компании больше никого нет — и данные ` +
      `кабинета компании.\n\nПередумали — до этой даты войдите в кабинет и ` +
      `нажмите «Отменить удаление»: ${publicUrl}/app/\n\n` +
      `Если это были не вы, срочно войдите и смените пароль.\n`,
  };
}

module.exports = { codeLetter, alreadyLetter, deletionLetter };
