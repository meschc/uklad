import { FlaskConical } from "lucide-react";
import { useT } from "@/lib/i18n";

/**
 * Пометка «это демо» над лентой переписки.
 *
 * Подпорка прототипа, парная к `useChatDemoReply`: там собеседник отвечает сам
 * через несколько секунд, здесь про это сказано вслух. Оба файла удаляются
 * одним движением, когда появится сервер.
 *
 * Почему это не комментарий в коде, который там и так есть. Комментарий читает
 * тот, кто открыл файл, а человек, которому показывают систему, файлов не
 * открывает: он пишет сообщение, через семь секунд получает ответ и делает
 * единственный доступный вывод — склады на Укладе отвечают мгновенно. Дальше он
 * пересказывает этот вывод кому-то ещё, и мы уже не врали, но уже наврали.
 *
 * Почему одна плашка на ленту, а не значок у каждой реплики. Придумана здесь
 * вся переписка целиком, включая историю до входа, — значок пришлось бы вешать
 * на каждое сообщение, и лента превратилась бы в перечисление того, чего нет,
 * вместо демонстрации того, что есть.
 */
export function ChatDemoNote() {
  const t = useT();

  return (
    <div className="flex items-start gap-2.5 border-b border-border bg-muted/40 px-4 py-2.5">
      <FlaskConical className="mt-px size-3.5 shrink-0 text-muted-foreground" />
      <p className="text-[11px] leading-relaxed text-muted-foreground">
        <span className="font-medium text-foreground/80">{t("chat.demo")}</span>{" "}
        {t("chat.demoHint")}
      </p>
    </div>
  );
}
