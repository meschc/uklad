import { cva, type VariantProps } from "class-variance-authority";

/**
 * Надзаголовок — подпись над полем, группой или колонкой: «ТОВАР», «КОЛИЧЕСТВО»,
 * «СМЕНА». В интерфейсе склада их больше полусотни, и до этого файла они были
 * написаны шестью разными способами: 10 и 11 пикселей, три начертания, а в паре
 * мест ещё и `text-xs`. Разница в один пиксель незаметна на своём экране и
 * отлично видна, когда два таких экрана стоят рядом.
 *
 * Отсюда и форма: не компонент, а только классы. Надзаголовок бывает и `span`
 * внутри `label`, и `dt` в списке определений, и `th` в шапке таблицы, и `li` в
 * боковом меню — заворачивать всё это в один тег значило бы ломать разметку
 * ради вида. Элемент остаётся тот, что нужен по смыслу, а типографика приезжает
 * из одного места.
 *
 *   <span className={eyebrow()}>Товар</span>
 *   <dt className={eyebrow({ size: "xs", weight: "normal" })}>Статус</dt>
 *   <p className={eyebrow({ className: "mb-2" })}>Поля</p>
 *
 * По умолчанию — `text-xs` полужирным: так набрано подавляющее большинство
 * подписей, и новый экран, написанный без раздумий, попадёт в общий строй.
 *
 * Ступеней две, а было три. Сам этот файл собрали, чтобы развести 10 и 11
 * пикселей, — но развёл он их только по названиям: кегли остались набраны
 * числом, мимо шкалы (`fontSize` в tailwind.config.js), и модуль, который
 * держит типографику всего кабинета, оказался единственным местом, ею не
 * пользующимся. Теперь `xs` — это `text-2xs` (те же 10), а `sm` поднялся с 11
 * до `text-xs` (12) и сошёлся с бывшим `base`, который и был `text-xs` с самого
 * начала. Разницы в пиксель между `sm` и `base` не существовало на экране, а в
 * коде она заставляла выбирать — поэтому имя `base` убрано, а не оставлено
 * синонимом.
 */
export const eyebrow = cva("uppercase tracking-wide", {
  variants: {
    size: {
      /** 10 px — вторичные подписи: легенда графика, метки на плотных панелях. */
      xs: "text-2xs",
      /** 12 px — основной кегль подписи и заголовок боковой панели. */
      sm: "text-xs",
    },
    weight: {
      /** Без начертания — подпись рядом со значением, которое и должно быть заметнее. */
      normal: "",
      medium: "font-medium",
      semibold: "font-semibold",
    },
    tone: {
      /** Приглушённый — подпись служебная, читают её только когда ищут. */
      muted: "text-muted-foreground",
      /**
       * Цветом окружения. Нужен там, где надзаголовок и есть заголовок раздела
       * («СМЕНА», «ЗАЯВКИ»), или стоит на цветной плашке и должен взять её цвет.
       * Пустая строка, а не `text-foreground`: класс из `className` иначе
       * встал бы рядом с ним, и какой победит — решал бы порядок в CSS-файле.
       */
      current: "",
    },
  },
  defaultVariants: { size: "sm", weight: "semibold", tone: "muted" },
});

export type EyebrowVariants = VariantProps<typeof eyebrow>;
