import { cva, type VariantProps } from "class-variance-authority";

/**
 * Карточка — та самая плита, из которых собран весь интерфейс: панель графика,
 * блок настроек, строка списка, плитка склада на дашборде. Поверхность у них
 * одна и та же: скругление, рамка, фон карточки. В коде она была выписана
 * тридцать с лишним раз, и внутренний отступ уже гулял между 8, 12, 14 и 16
 * пикселями без всякой системы — просто как кому пришлось в тот день.
 *
 * Форма та же, что у [`eyebrow`](./eyebrow.ts): не компонент, а классы. Карточка
 * бывает `section`, `div`, `ul`, `li`, `aside` и даже `button` (плитка склада
 * кликабельна), и оборачивать всё это в один тег значило бы портить разметку
 * ради вида.
 *
 *   <section className={card()}>…</section>
 *   <div className={card({ className: "flex flex-col gap-3" })}>…</div>
 *   <aside className={card({ pad: "none", className: "overflow-hidden" })}>…</aside>
 *
 * Раскладка внутри — `flex`, `gap`, `divide-y` — остаётся на месте вызова: это
 * про содержимое, а не про поверхность, и в вариант её выносить не за чем.
 *
 * По умолчанию `p-4`: так набрано две трети карточек, и новый экран попадёт в
 * общий строй, даже если про отступ не думали.
 */
export const card = cva("rounded-xl border border-border bg-card", {
  variants: {
    pad: {
      /**
       * Без отступа — когда содержимое само рисует свои поля: список с
       * разделителями во всю ширину, шапка на цветной подложке, окно.
       */
      none: "",
      /** 8 px — плотный список внутри карточки. */
      xs: "p-2",
      /** 12 px — строка списка, которая сама карточка. */
      sm: "p-3",
      /** 14 px — плитка в сетке: чуть теснее блока, чтобы их было видно как ряд. */
      md: "p-3.5",
      /** 16 px — блок раздела. */
      lg: "p-4",
    },
  },
  defaultVariants: { pad: "lg" },
});

export type CardVariants = VariantProps<typeof card>;
