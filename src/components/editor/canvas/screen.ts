import type { CellRect } from "@/lib/types";

/**
 * Экранный слой холста: чем меряется то, что нарисовано поверх плана.
 *
 * Сам план лежит в мировых координатах — клетках сетки, — и живёт внутри
 * scale-слоя. Всё, что рисуется над ним (выделение, ручки, рамки рядов,
 * превью), стоит уже в экранных пикселях: иначе толщина линий и размер ручек
 * менялись бы вместе с зумом. Перевод между этими двумя системами — ровно один,
 * и его тип объявлен здесь.
 */

/** Прямоугольник в экранных px — то, во что превращается мировой. */
export interface ScreenRect {
  left: number;
  top: number;
  width: number;
  height: number;
}

/**
 * Перевод мирового прямоугольника в экранный.
 *
 * `gap` (мировые px) поджимает прямоугольник со всех сторон — чтобы контуры,
 * отслеживающие модуль (выделение, ручки, наложение), совпадали с его заливкой,
 * которая стоит с зазором (п.4b). Слот-индикаторы (превью, якорь, призрак)
 * зовут без gap и остаются во всю клетку.
 */
export type ToScreen = (rect: CellRect, gap?: number) => ScreenRect;

/** Ручка ресайза: сторона или угол выделенного модуля. */
export type Handle = "n" | "s" | "e" | "w" | "ne" | "nw" | "se" | "sw";

