// ---------------------------------------------------------------------------
// Операции склада и учёт услуг.
//
// Склад продаёт продавцу не «систему», а операции: принять паллету, пересчитать
// штуку, наклеить код, собрать заказ, увезти рейс. Каждая из них — строка в
// счёте, поэтому у каждой должен остаться след: что сделали, сколько, кто и для
// чьего товара. Здесь три вещи: вид услуги, задание на операцию и настройка
// склада — какие операции он вообще оказывает и почём.
// ---------------------------------------------------------------------------

/**
 * Вид услуги. Первые пять система считает сама по фактам, которые уже пишет
 * (паллеты, тара, события приёмки, сборка, рейсы), — заводить на них задание
 * руками значило бы посчитать одно и то же дважды. Остальные выполняются
 * заданием: их факт появляется только тогда, когда сотрудник его закрыл.
 */
export type ServiceKind =
  // считаются сами
  | "cargo_pallet"
  | "cargo_box"
  | "item_receiving"
  | "picking"
  | "loading"
  // выполняются заданием
  | "unloading"
  | "quality_check"
  | "marking"
  | "honest_sign"
  | "repacking"
  | "kitting"
  | "packing"
  | "fbo_box"
  | "palletizing"
  | "returns"
  | "inventory"
  | "photo";

/** Единица, в которой услуга считается и продаётся. */
export type ServiceUnit = "pallet" | "box" | "unit" | "order" | "trip" | "vehicle" | "cell";

export type TaskStatus = "open" | "in_progress" | "done" | "cancelled";

/**
 * Задание на операцию. Плоское, как будущая строка таблицы: вид, сколько,
 * для какого продавца и кто сделал. Время начала и конца нужны и для счёта
 * (дата услуги — дата закрытия), и для журнала действий сотрудника.
 */
export interface WarehouseTask {
  id: string;
  kind: ServiceKind;
  status: TaskStatus;
  /** Объём в единицах услуги: штук, коробов, паллет. */
  qty: number;
  /** Чей товар — продавцу выставляется счёт. */
  partnerId?: string;
  /** Кто выполняет. Пусто — задание ещё никому не назначено. */
  staffId?: string;
  note?: string;
  createdAt: number;
  startedAt?: number;
  doneAt?: number;
}

/**
 * Какие операции оказывает склад и почём. Выключенная операция не
 * предлагается в заданиях и не попадает в отчёт: маленький склад видит три
 * шага, большой — двенадцать.
 */
export interface ServiceSettings {
  enabled: Partial<Record<ServiceKind, boolean>>;
  /** Цена за единицу, ₽. Пусто — цена не задана, сумма в отчёте не считается. */
  prices: Partial<Record<ServiceKind, number>>;
}

/**
 * Строка журнала операций — один факт оказанной услуги. Журнал не хранится:
 * он каждый раз собирается из заданий и фактов приёмки и отгрузки, поэтому не
 * может разойтись с ними.
 */
export interface OperationEntry {
  id: string;
  kind: ServiceKind;
  qty: number;
  at: number;
  staffId?: string;
  partnerId?: string;
  source: "auto" | "task";
}
