// ---------------------------------------------------------------------------
// Товар и его категории (ТЗ, разд. 2.5, 3.8). Набор категорий и доп.полей
// редактируется в интерфейсе, поэтому здесь только форма данных и стартовый
// список — ничего зашитого намертво.
// ---------------------------------------------------------------------------

export const PRODUCT_CATEGORIES = [
  "Одежда",
  "Электроника",
  "Бытовая техника",
  "Продукты",
  "Инструменты",
  "Мебель",
] as const;

/**
 * Категория товара — свободная строка: набор категорий редактируется в
 * интерфейсе и живёт в сторе (`categories`), а `PRODUCT_CATEGORIES` остаётся
 * стартовым списком для нового склада (п.15).
 */
export type ProductCategory = string;

/**
 * Товар. Обязательные атрибуты по ТЗ: артикул/SKU, штрихкод, категория,
 * фото (для демо генерируется), габариты Ш×В×Г в см с десятыми. Вес — опционально.
 */
export interface Product {
  id: string;
  sku: string;
  barcode: string;
  name: string;
  category: ProductCategory;
  widthCm: number;
  heightCm: number;
  depthCm: number;
  weightKg?: number;
  /** Ссылка на карточку товара (сайт/1С). Необязательна. */
  url?: string;
  /** Ссылка на изображение товара — показывается в карточке и таблице. */
  imageUrl?: string;
  /** Партнёр-продавец, чей это товар (`Partner.id`). */
  partnerId?: string;
}

// --- Поля категории: конструктор (ТЗ, разд. 2.5, 3.8) ------------------------

/** Тип доп.поля категории. */
export type FieldType = "text" | "number" | "select";

/**
 * Доп.поле категории (ТЗ, разд. 3.8): «имя + тип поля», уникальное название.
 * Задаётся заранее для категории или добавляется вручную через «настроить поля».
 */
export interface CategoryField {
  id: string;
  category: ProductCategory;
  name: string;
  type: FieldType;
  /** Варианты для type === "select". */
  options?: string[];
}
