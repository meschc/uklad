export const CELLS_MIN = 1;
export const CELLS_MAX = 10;

/** Конфигурация полок/ячеек новой секции по умолчанию. */
export const DEFAULT_SHELF_COUNT = 3;
export const DEFAULT_SHELF_CELLS = 4;

/**
 * Как устроена адресация на конкретном складе. Схемы у всех разные, поэтому
 * уровни адреса настраиваются, а не зашиты намертво (ТЗ, разд. 2.1).
 */
export interface AddressingConfig {
  /**
   * Участвует ли «этаж» отдельным уровнем адреса. Для складов с одним этажом
   * номер этажа избыточен. По умолчанию (и для старых данных без поля) — да.
   */
  useFloor?: boolean;
  /** Участвует ли «ряд» отдельным уровнем: этаж-ряд-секция-полка-ячейка. */
  useRows: boolean;
  /** Полка №1 — нижняя (обычно) или верхняя. */
  shelfOrder: "bottomUp" | "topDown";
  /** Разделитель уровней в строке адреса. */
  separator: string;
  /** Пользователь уже ответил на вопросы — больше не предлагаем настроить. */
  configured: boolean;
}

export const DEFAULT_ADDRESSING: AddressingConfig = {
  useFloor: true,
  useRows: false,
  shelfOrder: "bottomUp",
  separator: "-",
  configured: false,
};

/**
 * Адрес ячейки: этаж/ряд — секция — полка — ячейка (напр. `32-19-20-3`).
 * Индексы полки/ячейки — с нуля, в адресе показываются с единицы.
 */
export interface CellAddress {
  floorId: string;
  moduleId: string;
  shelfIndex: number;
  cellIndex: number;
}

/**
 * Шаблон раскладки полок/ячеек в библиотеке (ТЗ, разд. 2.3 —
 * «отдельная библиотека шаблонов, как компоненты в Figma»).
 * Хранит только раскладку (число ячеек по полкам), без привязки к секции.
 */
export interface ShelfTemplate {
  id: string;
  name: string;
  cells: number[]; // число ячеек на каждой полке, длина = число полок
}

/**
 * Один модуль в шаблоне раскладки (#38). Смещения `dx/dy` — от левого верхнего
 * угла габарита всей группы, чтобы штамп не зависел от того, где группу
 * сохранили. Полки хранятся как число ячеек по полкам (id перегенерируются при
 * штампе), по образцу ShelfTemplate.
 */
export interface LayoutModuleSpec {
  type: ModuleType;
  dx: number;
  dy: number;
  w: number;
  h: number;
  rotation?: 0 | 90 | 180 | 270;
  realWidthCm?: number;
  realDepthCm?: number;
  realHeightCm?: number;
  shelves?: number[];
}

/**
 * Шаблон раскладки модулей (#38): сохранённая группа секций/проходов/лестниц,
 * которую можно штамповать на план — как компонент в Figma, но из нескольких
 * модулей, а не из раскладки полок одной секции.
 */
export interface LayoutTemplate {
  id: string;
  name: string;
  modules: LayoutModuleSpec[];
}

/**
 * Стороннность ряда и порядок нумерации секций внутри него.
 *
 * `sided`:
 *   - "auto" (по умолчанию) — определяем по форме: две параллельные линии
 *     секций через проход = двусторонний, одна линия = односторонний;
 *   - "two"  — двусторонний: одна сторона нечёт, другая чёт (складская классика);
 *   - "one"  — односторонний: секции нумеруются подряд.
 * `oddSide` — какая сторона получает нечётные номера (для двустороннего):
 *   "near" — ближняя (меньшая координата поперёк), "far" — дальняя.
 */
export interface RowConfig {
  number: number;
  sided?: "auto" | "one" | "two";
  oddSide?: "near" | "far";
}

/** Найденный по образцу ряд-кандидат: набор секций и его габарит. */
export interface RowCandidate {
  ids: string[];
  rect: CellRect;
}

/** Кандидат в предложении «продолжить ряды» с назначенным номером и галочкой. */
export interface RowProposalItem extends RowCandidate {
  number: number;
  checked: boolean;
}

/**
 * Предложение авто-продолжения рядов по образцу (ТЗ, разд. 3.5). Возникает
 * после закрепления ряда: система находит такие же по форме нераспределённые
 * группы секций и предлагает пронумеровать их подряд. Состояние временное —
 * в persist не попадает.
 */
export interface RowProposal {
  anchor: number;
  candidates: RowProposalItem[];
}

export interface Floor {
  id: string;
  name: string;
  modules: PlacedModule[];
  /**
   * Собственный номер этажа в адресе. Задаётся вручную и НЕ обязан совпадать
   * с позицией в списке: на реальном складе мезонин может быть «этажом 3»,
   * даже если он второй по порядку. Не задан — берётся позиция (совместимость
   * со старыми данными).
   */
  number?: number;
  /**
   * Конфигурация рядов этажа (стороннность, порядок нумерации). Опциональна и
   * переживает рехайдрацию: старые данные без неё работают как `sided: "auto"`.
   */
  rows?: RowConfig[];
  /**
   * Этаж-алиас (ТЗ, разд. 3.5 — тиражирование): если задан, этаж зеркалит
   * раскладку этажа-источника (обычно первого — «основного блока»). Правка
   * любого связанного этажа идёт в источник, все алиасы обновляются разом.
   * Разрыв связи материализует независимую копию. Опционально — старые данные
   * без поля остаются самостоятельными этажами.
   */
  aliasOf?: string;
}

