import type { CellAddress } from "./plan";

/** Товар внутри коробки: артикул + количество. */
export interface BoxLine {
  productId: string;
  qty: number;
}

/** Коробка приёмки: физический короб со своим ярлыком Code128. */
export interface Box {
  id: string;
  barcode: string; // Code128, формат УК-BOX-000123
  createdAt: number;
  lines: BoxLine[];
  palletId?: string;
  /** Где физически стоит коробка. Пока не размещена — undefined. */
  address?: CellAddress;
}

/** Паллета: группа коробок под одним ярлыком. */
export interface Pallet {
  id: string;
  barcode: string; // формат УК-PLT-000045
  createdAt: number;
  boxIds: string[];
  address?: CellAddress;
}

/**
 * Откуда пришёл список ожидаемой поставки. Каждый источник — тонкий адаптер к
 * общему формату строк (см. `shipmentSources.ts`); "manual" — универсальный
 * шаблон для поставщика без своей системы учёта.
 */
export type ShipmentSource = "1c" | "moysklad" | "honest-sign" | "manual";

export interface ExpectedShipmentLine {
  /** Собственный id строки — на него ссылается ReceivingEvent. */
  id: string;
  productId: string;
  expectedQty: number;
  /** Растёт по мере приёмки; сверяется при вводе фактического количества. */
  receivedQty: number;
  /**
   * Дропшиппинг (п.10.1): id заявок, под которые это количество забронировано
   * ЕЩЁ ДО прихода машины. Продавец продаёт то, чего физически нет на складе,
   * но что уже заказано у поставщика.
   */
  reservedFor?: string[];
}

export type ShipmentStatus = "pending" | "receiving" | "closed";

/**
 * Ожидаемая поставка — единственная точка стыка кабинета с витриной.
 *
 * Витринная сделка (`site/data/deals.ts`) доходит до кабинета ровно здесь:
 * «готов принять» не заводит в учёте ничего, первая сущность появляется вместе
 * с датой первой машины. Ссылка на сделку (`deal_id`) появится в тот же день,
 * что и настоящая приёмка заявки с витрины, — не раньше: сейчас она была бы
 * пустой всегда. Подробно — `docs/adr/0005-styk-vitriny-i-kabineta.md`.
 */
export interface ExpectedShipment {
  id: string;
  source: ShipmentSource;
  /** Человекочитаемое имя партии («Поставка 12.08, Ромашка»). */
  title?: string;
  lines: ExpectedShipmentLine[];
  createdAt: number;
  status: ShipmentStatus;
  /** Когда поставку закрыли — досрочно или по факту набора всех строк. */
  closedAt?: number;
  /**
   * Кроссдокинг (п.10.1): товар не размещается на полку, а с рампы уходит
   * прямо в сборку заявки. В занятость (`buildOccupancy`) он не попадает —
   * не потому что мы забыли его учесть, а потому что он физически не хранится.
   */
  crossDock?: boolean;
}

/** Расхождение план/факт, зафиксированное оператором осознанно. */
export type Discrepancy = "shortage" | "overage";

/**
 * Факт приёмки одной позиции. Пишется каждый раз, когда оператор подтвердил
 * количество и уложил товар в коробку.
 */
export interface ReceivingEvent {
  id: string;
  productId: string;
  qty: number;
  boxId: string;
  staffId?: string;
  timestamp: number;
  /** Заполняется, если приёмка шла со сверкой. */
  expectedShipmentLineId?: string;
  /**
   * Заполняется, только если оператор подтвердил расхождение и пошёл дальше:
   * «недостача» (принято меньше ожидаемого) / «перестача» (больше). Если
   * сошлось или пересчитали и исправили — поля нет.
   */
  discrepancy?: Discrepancy;
}

/**
 * Шаг мастера приёмки. Порядок повторяет физику работы на рампе (п.18): сначала
 * под рукой появляется паллета, на неё открывают тару, в тару кладут товар — и
 * только закрытая тара едет на место. Паллета необязательна: мелкую поставку
 * принимают сразу в тару.
 */
export type ReceivingStep = "shipment" | "pallet" | "box" | "product" | "qty" | "place";

/**
 * Ход незакрытой приёмки (п.4.7).
 *
 * Живёт в сторе, а не в состоянии экрана: приёмка идёт часами и прерывается
 * постоянно — посмотреть задание, ответить в переписке, уточнить остаток.
 * Возвращаться после каждого такого шага к выбору поставки и заново искать свою
 * тару — это не «мелкое неудобство», а причина вести приёмку на бумаге.
 *
 * Здесь только то, что переживает перезагрузку: сам шаг, поставка, кто
 * принимает, открытые тара и паллета (по id — объекты берутся из стора) и
 * счётчик принятого за заход. Опознанный сканом товар, подсветка поля и
 * диалоги — в экране: они существуют ровно в момент работы.
 */
export interface ReceivingProgress {
  step: ReceivingStep;
  /** Поставка, которую сверяем; `null` — свободная приёмка без сверки. */
  shipmentId: string | null;
  /** Кто принимает. Пустая строка — не выбрали. */
  staffId: string;
  palletId: string | null;
  boxId: string | null;
  /** Принято этим кладовщиком за текущий заход — цифра «за смену» в полосе. */
  received: number;
}

/**
 * Путь заявки: принята → собирается → собрана → отгружена. «Собрана» и
 * «отгружена» разделены намеренно: для продавца это разные вещи — товар
 * снят с полок и товар физически уехал, и подрядчик отвечает за обе.
 */
export type RequestStatus = "new" | "in_progress" | "done" | "shipped" | "cancelled";

/** Рейс: одна машина увозит собранные заявки одного назначения. */
export interface Shipment {
  id: string;
  /** Назначение — то же, что в заявке (адрес текстом). */
  destination: string;
  /** Заявки, уехавшие этим рейсом. */
  requestIds: string[];
  /** Номер машины / водитель — как записал кладовщик. */
  vehicle?: string;
  /** Кто отгрузил (id сотрудника) и когда. */
  staffId?: string;
  shippedAt: number;
}

/**
 * Заявка продавца на отгрузку. Спроектирована как будущая строка таблицы:
 * плоская, без вложенных объектов кроме адреса.
 *
 * Это не заявка-подбор с витрины и не её продолжение: здесь отгружают товар,
 * который уже лежит на складе, и таких заявок за месяц десятки. Со стыком
 * витрины у неё нет ничего общего — стык проходит через `ExpectedShipment`.
 */
export interface FulfillmentRequest {
  id: string;
  productId: string;
  qty: number;
  targetAddress?: CellAddress;
  /** Назначение текстом, если адрес неизвестен. */
  note?: string;
  /** Дата прибытия машины; общая на весь пакет при массовом импорте. */
  truckDate?: number;
  /**
   * Машина / водитель, если продавец знает их заранее: он сам организует
   * вывоз, и складу не нужно выяснять это по телефону в момент погрузки.
   */
  vehicle?: string;
  status: RequestStatus;
  createdAt: number;
  updatedAt: number;
  /** Когда заявку взяли в работу — нужно для метрики времени сборки. */
  startedAt?: number;
  /** Сколько единиц уже собрано на экране «Сборка». */
  pickedQty?: number;
  /** Закрыта частично: собрали меньше запрошенного и отметили это явно. */
  partial?: boolean;
  /** Рейс, которым заявка уехала (после отгрузки). */
  shipmentId?: string;
  shippedAt?: number;
  /**
   * Дропшиппинг (п.10.1): заявка ждёт эту ожидаемую поставку. Товара на складе
   * может не быть вовсе — он забронирован в строке `ExpectedShipmentLine`.
   */
  reservedShipmentId?: string;
}
