// Наклейки на тару (п.6): что печатаем и на какой ленте. Шаблон — не «дизайн»,
// а сохранённая настройка печати; список элементов закрытый.
// ---------------------------------------------------------------------------

/**
 * Элементы наклейки (п.6). Список закрытый: наклейка на коробе живёт в мире
 * термопринтера 58 мм и грязных перчаток, произвольная вёрстка на ней не нужна
 * — нужен выбор «что из известного печатать».
 *
 * Набор взят с логистической этикетки GS1: блок отправителя (логотип, склад),
 * текстовая интерпретация (номер места, КИЗ, дата) и сам код. Отсюда же
 * «Место N из M» — на складе по нему считают, вся ли партия доехала.
 */
export type LabelElement =
  | "logo" // знак компании
  | "title" // «Тара» / «Паллета»
  | "warehouse" // название склада
  | "seq" // «Место 1 из 12»
  | "code" // читаемый номер под кодом
  | "date" // дата печати
  | "fragile" // «Хрупкое»
  | "mark" // код маркировки (мок «Честного знака»)
  | "note"; // произвольная строка

/** Как повёрнута наклейка: код снизу (вертикально) или слева (горизонтально). */
export type LabelLayout = "vertical" | "horizontal";

/**
 * Чем кодировать номер. QR держит больше и читается камерой телефона, но его
 * не берут дешёвые лазерные «пистолеты» — на складах, где они стоят, нужен
 * линейный Code128. Поэтому это выбор склада, а не наше решение за него.
 */
export type LabelCodeType = "qr" | "barcode";

/**
 * Шаблон наклейки: размер печати + набор элементов. Шаблон — это не «дизайн»,
 * а сохранённая настройка печати: у склада обычно два-три размера ленты, и
 * каждый раз выставлять их заново — потерянное время.
 */
export interface LabelTemplate {
  id: string;
  name: string;
  /** Физический размер наклейки, мм. */
  widthMm: number;
  heightMm: number;
  layout: LabelLayout;
  codeType: LabelCodeType;
  elements: LabelElement[];
  /**
   * Доля наклейки под код, 0.3…1. Именно доля, а не жёсткий размер: текст
   * забирает своё первым, код занимает остаток — поэтому даже на 100 %
   * содержимое не выдавливается за край.
   */
  codeScale: number;
  /** Текст элемента "note". */
  note?: string;
  /** Знак компании, data-URL. Уменьшается при загрузке — localStorage не резиновый. */
  logoUrl?: string;
  createdAt: number;
}

export const LABEL_SIDE_MIN_MM = 20;
export const LABEL_SIDE_MAX_MM = 210;
export const LABEL_CODE_MIN = 0.3;
export const LABEL_CODE_MAX = 1;
/** Ширина, до которой ужимается загруженный логотип, px. */
export const LABEL_LOGO_MAX_PX = 240;

/** Ходовые размеры термоэтикеток — с них начинают, а не с пустых полей. */
export const LABEL_SIZE_PRESETS: { w: number; h: number }[] = [
  { w: 43, h: 25 },
  { w: 58, h: 40 },
  { w: 58, h: 60 },
  { w: 100, h: 70 },
  { w: 100, h: 150 },
];
