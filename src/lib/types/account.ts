/** Язык интерфейса (ТЗ, разд. 3.3). */
export type Lang = "ru" | "en";

/** Тема оформления (ТЗ, разд. 3.3). */
export type Theme = "light" | "dark";

/**
 * Верхний экран приложения. Первые четыре — исходный контур (вход → кабинет →
 * редактор / профиль), остальные — фулфилмент-контур, доступный из бокового
 * рельса навигации.
 */
export type AppView =
  | "login"
  | "dashboard"
  | "editor"
  | "profile"
  | "receiving"
  | "labels"
  | "documents"
  | "lookup"
  | "integrations"
  | "tasks"
  | "picking"
  | "staff"
  | "analytics"
  | "spec"
  | "seller"
  | "chat";

/**
 * Аккаунт (ТЗ, разд. 3.2): личный или компании. От типа зависит, что
 * показываем в шапке кабинета.
 */
export interface Account {
  type: "personal" | "company";
  /** Имя пользователя. */
  name: string;
  /** Название компании (для type === "company"). */
  org?: string;
  /** Подпись/роль — для шапки. */
  title?: string;
  /** ИНН компании: по нему подтягиваются остальные реквизиты (п.4). */
  inn?: string;
  kpp?: string;
  ogrn?: string;
  legalAddress?: string;
}

/** Настройки профиля (ТЗ, разд. 3.3): имя, email, тема, язык. */
export interface Profile {
  name: string;
  email: string;
  theme: Theme;
  language: Lang;
  /** Рисовать ли внутреннюю разбивку секции на полки. По умолчанию да. */
  showShelves?: boolean;
}

/** Роль текущего пользователя: склад или продавец (переключатель режима). */
export type UserRole = "warehouse" | "seller";

/**
 * Пользователь системы (п.0.5). Реального логина ещё нет — сегодня это тот же
 * локальный «переключатель роли», но уже в той форме, в которую ляжет
 * настоящая авторизация Supabase: строка таблицы `users` один в один.
 */
export interface User {
  id: string;
  email: string;
  role: UserRole;
  /** Склад, к которому привязан пользователь. */
  warehouseId: string;
  name?: string;
}

/**
 * Сессия: кто сейчас работает. `token` сегодня — локальный мок, сгенерированный
 * при входе; когда появится backend, здесь будет настоящий JWT, а форма данных
 * вокруг него не изменится.
 */
export interface Session {
  user: User;
  token: string;
  startedAt: number;
}
