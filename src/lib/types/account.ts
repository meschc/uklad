// (ТЗ, разд. 3.1–3.4). Форма `User`/`Session` заранее совпадает с будущими
// таблицами Supabase — при подключении backend меняется источник, не модель.
// ---------------------------------------------------------------------------

/** Язык интерфейса (ТЗ, разд. 3.3). */
export type Lang = "ru" | "en";

/** Тема оформления (ТЗ, разд. 3.3). */
export type Theme = "light" | "dark";

/**
 * Верхний экран приложения. Первые четыре — исходный контур (вход → кабинет →
 * редактор / профиль), остальные — фулфилмент-контур, доступный из бокового
 * рельса навигации.
 */
export type AppView =
  | "login"
  | "dashboard"
  | "editor"
  | "profile"
  | "receiving"
  | "labels"
  | "documents"
  | "lookup"
  | "integrations"
  | "tasks"
  | "picking"
  | "operations"
  | "staff"
  | "analytics"
  | "spec"
  | "seller"
  | "chat"
  | "workstation";

/**
 * Аккаунт (ТЗ, разд. 3.2): личный или компании. От типа зависит, что
 * показываем в шапке кабинета.
 */
export interface Account {
  type: "personal" | "company";
  /** Имя пользователя. */
  name: string;
  /** Название компании (для type === "company"). */
  org?: string;
  /** Подпись/роль — для шапки. */
  title?: string;
  /** ИНН компании: по нему подтягиваются остальные реквизиты (п.4). */
  inn?: string;
  kpp?: string;
  ogrn?: string;
  legalAddress?: string;
}

/** Настройки профиля (ТЗ, разд. 3.3): имя, email, тема, язык. */
export interface Profile {
  name: string;
  email: string;
  theme: Theme;
  language: Lang;
  /** Рисовать ли внутреннюю разбивку секции на полки. По умолчанию да. */
  showShelves?: boolean;
  /** Системные уведомления о сообщениях, когда вкладка скрыта. По умолчанию нет: браузер спрашивает разрешение. */
  chatNotify?: boolean;
  /** Показывать ли в уведомлении текст сообщения. По умолчанию да; нет — только кто написал. */
  chatNotifyPreview?: boolean;
}

/** Роль текущего пользователя: склад или продавец (переключатель режима). */
export type UserRole = "warehouse" | "seller";

/**
 * Пользователь системы (п.0.5). Реального логина ещё нет — сегодня это тот же
 * локальный «переключатель роли», но уже в той форме, в которую ляжет
 * настоящая авторизация Supabase: строка таблицы `users` один в один.
 */
export interface User {
  id: string;
  email: string;
  role: UserRole;
  /** Склад, к которому привязан пользователь. */
  warehouseId: string;
  /**
   * Продавец — какой он партнёр склада (`Partner.id`). Продавец видит ТОЛЬКО
   * товар, который склад за этим партнёром закрепил. Нет поля — не видит
   * ничего: чужой товар показывать нельзя ни при каких настройках.
   */
  partnerId?: string;
  name?: string;
}

/**
 * Сессия: кто сейчас работает. `token` сегодня — локальный мок, сгенерированный
 * при входе; когда появится backend, здесь будет настоящий JWT, а форма данных
 * вокруг него не изменится.
 */
export interface Session {
  user: User;
  token: string;
  startedAt: number;
}

/**
 * Тариф аккаунта — те же три готовых тарифа, что на сайте (`site/data/plans`,
 * таблица отличий в `warehouses/tariffsData.ts`). Оплаты в прототипе нет:
 * тариф пока выбирается в профиле, а придёт из биллинга сервера.
 */
export type TariffId = "operator" | "warehouse" | "start";

/** Персональный менеджер тарифа «Оператор». Назначает его Уклад, не клиент. */
export interface Manager {
  name: string;
  phone?: string;
  email?: string;
}

/** Настройки резервных копий (тарифы на сайте, группа «Данные»). */
export interface BackupSettings {
  /** Напоминать сделать копию раз в N дней; 0 — не напоминать. */
  remindEveryDays: number;
  /** Когда последний раз скачан архив (мс). Нет — копию ещё не делали. */
  lastBackupAt?: number;
  /** «Напомнить позже» откладывает напоминание до этого момента (мс). */
  snoozedUntil?: number;
  /** Еженедельная копия на почту — только «Склад» и «Оператор». */
  emailWeekly: boolean;
}

export interface Subscription {
  tariff: TariffId;
  manager?: Manager;
  backup: BackupSettings;
}
