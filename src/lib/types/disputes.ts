/**
 * Спорное: то, что сотрудник у стола решить не вправе. Недостачу и ошибки скана
 * он не оформляет сам — тара уходит старшему, а в системе остаётся запись, по
 * которой видно, кто, когда и что нашёл. Решает старший смены.
 */
export type DisputeKind =
  /** При закрытии тары в ней осталось то, что должны были упаковать. */
  | "shortage"
  /** Отсканировали товар, которого в таре нет. */
  | "not_in_tote"
  /** Товара больше, чем просили заказы. */
  | "extra"
  /** Товар, который по правилам склада упаковывать нельзя. */
  | "not_packable"
  /**
   * Принято сверх строки поставки или без поставки. Заводит сервер сам при
   * приёмке со стола: товар появился на складе, и старший должен это увидеть.
   */
  | "receive_overage"
  /**
   * Инвентаризация: при пересчёте тары нашли меньше, чем по учёту. Заводит
   * сервер сам по факту пересчёта; старший списывает недостачу или закрывает
   * без правки учёта (товар нашёлся).
   */
  | "inventory_short"
  /**
   * Инвентаризация: нашли больше, чем по учёту. Старший оприходует излишек в
   * ту же тару или закрывает без правки учёта.
   */
  | "inventory_over";

/**
 * Что решил старший: вернуть на место, переложить в другую тару или списать.
 * Лишнее с приёмки оставляют на складе (`accepted`) или списывают — вернули
 * поставщику.
 */
export type DisputeResolution = "returned" | "moved" | "written_off" | "accepted";

export interface Dispute {
  id: string;
  kind: DisputeKind;
  /** Тара, с которой работали, и её код на момент находки. */
  boxId?: string;
  toteCode?: string;
  productId?: string;
  qty: number;
  /** Кто нашёл (сотрудник у стола) и когда. */
  raisedBy: string;
  raisedAt: number;
  /** Кто решил: id сотрудника или «manager» (руководитель из кабинета). */
  resolvedBy?: string;
  resolvedAt?: number;
  resolution?: DisputeResolution;
  note?: string;
}
