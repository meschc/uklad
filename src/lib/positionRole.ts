/**
 * Роль по должности — подсказка, когда сотрудника заводят или меняют ему
 * должность (Кирилл 14.11: «должность — старший смены, роль у него должна быть
 * как у старшего»). Должность — подпись в документах, роль — права; связаны
 * они только этой подсказкой, руководитель может выбрать другую роль.
 *
 * Сопоставление по началу слов, без регистра: должность могли ввести руками
 * («старший смены», «Ст. кладовщик» уже не узнаем — тогда подсказки нет).
 */
const RULES: [RegExp, string][] = [
  [/^(управляющ|заведующ|начальник склада|директор)/i, "Начальник склада"],
  [/^(старш|начальник смены|бригадир)/i, "Старший смены"],
  [/^(приёмщ|приемщ|оператор приёмки|оператор приемки)/i, "Приёмщик"],
  [/^(комплектовщ|сборщ)/i, "Сборщик"],
  [/^упаковщ/i, "Упаковщик"],
  [/^(кладовщ|водитель|грузчик|оператор)/i, "Кладовщик"],
];

/** Имя стандартной роли для должности или `null`, если подсказки нет. */
export function roleForPosition(position: string): string | null {
  const p = position.trim();
  if (!p) return null;
  for (const [re, role] of RULES) if (re.test(p)) return role;
  return null;
}

/** Id стандартной роли для должности среди ролей компании. */
export function suggestRoleId(
  position: string,
  roles: { id: string; name: string; builtIn: boolean }[],
): string | null {
  const name = roleForPosition(position);
  return name ? (roles.find((r) => r.builtIn && r.name === name)?.id ?? null) : null;
}
