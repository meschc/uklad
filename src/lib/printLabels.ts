/**
 * Печать и отметка «напечатан». Отметка ставится по `afterprint`, а не по
 * нажатию: если человек закрыл окно печати, ярлыки напечатанными не считаются.
 * Браузер не отличает «Печать» от «Отмена»: `afterprint` приходит после
 * закрытия окна в обоих случаях. Поэтому отметка — «отправлено на печать», а
 * не «лента вышла»; перепечатать можно в любой момент.
 */
export function printLabels(onPrinted?: () => void): void {
  if (onPrinted) window.addEventListener("afterprint", onPrinted, { once: true });
  // Кадр на отрисовку печатного блока, который только что появился в дереве.
  requestAnimationFrame(() => window.print());
}
