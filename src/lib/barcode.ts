const C128_START_B = 104;
const C128_STOP = 106;
/** Хвостовые две полосы после стоп-символа (по стандарту). */
const C128_TERMINATOR = "11";

/**
 * Строка модулей ('1' — штрих, '0' — пробел) для Code128 B.
 * Возвращает null, если строка пуста или содержит символы вне ASCII 32…126:
 * набор B кириллицу не кодирует, и молча печатать «почти правильный» ярлык
 * хуже, чем не напечатать (сканер прочитает не то, что написано глазами).
 */
export function code128Modules(text: string): string | null {
  if (!text || text.length > 48) return null;
  const values: number[] = [];
  for (const ch of text) {
    const code = ch.codePointAt(0)!;
    if (code < 32 || code > 126) return null;
    values.push(code - 32);
  }
  let checksum = C128_START_B;
  values.forEach((v, i) => {
    checksum += v * (i + 1);
  });
  const parts = [
    C128[C128_START_B],
    ...values.map((v) => C128[v]),
    C128[checksum % 103],
    C128[C128_STOP],
    C128_TERMINATOR,
  ];
  return parts.join("");
}

/** Ширина порядкового номера в ярлыке: UK-BOX-000123. */
const SEQ_PAD = 6;

/**
 * Префиксы внутренних ярлыков — латиницей: код, набранный руками в чужой
 * раскладке или прочитанный вслух по телефону, не должен зависеть от языка.
 * Ввод с русской раскладки («УК-…») чинится в `normalizeCode` ниже.
 */
export const BOX_PREFIX = "UK-BOX-";
export const PALLET_PREFIX = "UK-PLT-";

export function generateBoxBarcode(seq: number): string {
  return BOX_PREFIX + String(Math.max(1, Math.round(seq))).padStart(SEQ_PAD, "0");
}

export function generatePalletBarcode(seq: number): string {
  return PALLET_PREFIX + String(Math.max(1, Math.round(seq))).padStart(SEQ_PAD, "0");
}

/**
 * Нормализация отсканированного/введённого кода перед сравнением: убираем
 * пробелы, приводим к верхнему регистру и чиним кириллические «УК» — их легко
 * набрать руками, не переключив раскладку.
 */
export function normalizeCode(raw: string): string {
  return raw
    .trim()
    .toUpperCase()
    .replace(/\s+/g, "")
    .replace(/^УК-/, "UK-")
    .replace(/^УK-/, "UK-")
    .replace(/^YK-/, "UK-");
}

/**
 * Печатный ярлык ячейки — это тот же адрес, что показан в интерфейсе.
 * Отдельного формата не заводим: иначе кладовщик увидел бы на полке одно,
 * а в программе другое.
 */
export function cellBarcode(
  warehouse: Warehouse,
  addr: CellAddress,
): string | null {
  return formatAddress(warehouse, addr);
}

// --- Мок «Честного знака» ----------------------------------------------------

/**
 * Разобранный код маркировки. Мок: в реальной жизни это разбор DataMatrix по
 * GS1-AI (01 — GTIN, 21 — серийный номер) с последующей проверкой в ГИС МТ.
 * Здесь только детерминированный вывод из строки, чтобы неучтённый товар
 * получал стабильную заготовку карточки.
 */
export interface HonestSignScan {
  raw: string;
  gtin: string; // мок, выводится детерминированно из raw
  serial: string; // мок
  isMocked: true;
}

/** Максимальная длина сырого кода, которую вообще принимаем к разбору. */
const HONEST_SIGN_MAX = 256;

/** Простой детерминированный хеш строки — основа мок-GTIN. */
function hashString(s: string): number {
  let h = 2166136261;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return Math.abs(h);
}

/**
 * Мок разбора кода «Честного знака». Настоящий код DataMatrix выглядит как
 * `01<14 цифр GTIN>21<серийник>…`; если такая структура узнаётся — берём поля
 * из неё, иначе выводим их из строки детерминированно.
 *
 * Вход не доверяем: строка приходит со сканера, её длину режем, управляющие
 * символы (в т.ч. GS-разделитель) выбрасываем — это то, что дальше уедет в
 * localStorage как штрихкод нового товара.
 */
export function parseHonestSignMock(raw: string): HonestSignScan {
  const clean = raw
    .slice(0, HONEST_SIGN_MAX)
    // eslint-disable-next-line no-control-regex
    .replace(/[\x00-\x1f\x7f]/g, "")
    .trim();

  const structured = /^01(\d{14})21([A-Za-z0-9\-._/]{1,20})/.exec(clean);
  if (structured) {
    return {
      raw: clean,
      gtin: structured[1],
      serial: structured[2],
      isMocked: true,
    };
  }

  const h = hashString(clean || "empty");
  const gtin = String(h).padStart(14, "0").slice(-14);
  const serial = h.toString(36).toUpperCase().padStart(6, "0").slice(-6);
  return { raw: clean, gtin, serial, isMocked: true };
}

/**
 * Штрихкод товара по коду маркировки: последние 13 цифр GTIN достраиваем до
 * валидного EAN-13, чтобы заготовка карточки сразу имела печатаемый код.
 */
export function honestSignToEan13(scan: HonestSignScan): string {
  return toEan13(scan.gtin.slice(-12));
}
