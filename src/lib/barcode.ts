/**
 * Номера и коды склада.
 *
 *  — **EAN-13** — номер товара. Приходит извне (GS1), только цифры. Здесь
 *    живёт его проверка и генерация, но НЕ рисование: карточку товара и его
 *    печатный ярлык мы рисуем в QR (см. `lib/qr.ts`).
 *  — **UK-BOX- / UK-PLT-** — внутренние номера тары и паллет. Печатаем сами,
 *    поэтому формат наш: латиница и дефис, читаемые и с ободранной наклейки.
 *  — **Code128 B** — линейный штрихкод для наклеек тары: выбирается в
 *    конструкторе наравне с QR. Нужен там, где на складе стоят дешёвые
 *    лазерные «пистолеты»: они читают только одномерные коды, QR им не по
 *    зубам. Кириллицу подмножество B не кодирует — внутренние номера у нас
 *    латиницей как раз поэтому.
 */

/** Контрольная цифра EAN-13 по 12 цифрам (нечётные позиции ×1, чётные ×3). */
export function ean13CheckDigit(base12: string): number {
  let sum = 0;
  for (let i = 0; i < 12; i++) {
    const d = base12.charCodeAt(i) - 48;
    sum += i % 2 === 0 ? d : d * 3;
  }
  return (10 - (sum % 10)) % 10;
}

/** Достроить 12 цифр до полного EAN-13 контрольной цифрой. */
export function toEan13(base12: string): string {
  const digits = base12.replace(/\D/g, "").slice(0, 12).padEnd(12, "0");
  return digits + ean13CheckDigit(digits);
}

/** Проверка валидности готового 13-значного кода. */
export function isValidEan13(code: string): boolean {
  if (!/^\d{13}$/.test(code)) return false;
  return ean13CheckDigit(code.slice(0, 12)) === code.charCodeAt(12) - 48;
}

/**
 * Сгенерировать валидный EAN-13. Префикс 460 — диапазон GS1 России, дальше
 * случайные цифры и контрольная. Для демо годится; в проде номера выдаёт GS1.
 */
export function generateEan13(prefix = "460"): string {
  let base = prefix.replace(/\D/g, "").slice(0, 12);
  while (base.length < 12) base += Math.floor(Math.random() * 10);
  return toEan13(base);
}

