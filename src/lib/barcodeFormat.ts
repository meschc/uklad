/**
 * Штрихкод товара для глаза: цифры разделены так, как их печатают на упаковке.
 * `4600051070012` читается плохо, `4 600051 070012` — как на самом товаре
 * (Кирилл 23.11: «разделение хорошо работает визуально»). Только показ: в
 * данных, поиске и скане код остаётся сплошной строкой.
 *
 *  - EAN-13: 1 · 6 · 6 (первая цифра, затем две группы по шесть);
 *  - EAN-8: 4 · 4;
 *  - UPC-A (12): 1 · 5 · 5 · 1;
 *  - ISBN-13 (978/979…): префикс · группа · издатель и книга · контрольная.
 *    Длину издательского диапазона даёт реестр, которого у нас нет, поэтому
 *    после группы остаток делится условно (5 + 3 цифры); для сверки глазом
 *    этого хватает, а точной расстановки дефисов тут не обещаем;
 *  - ISBN-10: группа · издатель · книга · контрольная (1 · 5 · 3 · 1).
 * Всё остальное — наши ярлыки, DataMatrix, артикулы — без изменений.
 */
const SEP = " ";

/** Нарезать строку по длинам групп; остаток, если он есть, — последней группой. */
function groups(s: string, lens: number[]): string {
  const out: string[] = [];
  let at = 0;
  for (const n of lens) {
    out.push(s.slice(at, at + n));
    at += n;
  }
  if (at < s.length) out.push(s.slice(at));
  return out.join(SEP);
}

export function formatBarcode(code: string): string {
  const c = code.trim();
  if (/^\d{13}$/.test(c)) {
    // ISBN-13 — это EAN-13 с префиксом книжной продукции.
    if (/^97[89]/.test(c)) return groups(c, [3, 1, 5, 3, 1]);
    return groups(c, [1, 6, 6]);
  }
  if (/^\d{8}$/.test(c)) return groups(c, [4, 4]);
  if (/^\d{12}$/.test(c)) return groups(c, [1, 5, 5, 1]);
  if (/^\d{9}[\dXx]$/.test(c)) return groups(c, [1, 5, 3, 1]);
  return c;
}
