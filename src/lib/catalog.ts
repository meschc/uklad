/** Префикс артикула по категории — чтобы номера читались по группам. */
const SKU_PREFIX: Record<ProductCategory, number> = {
  Одежда: 1,
  Электроника: 2,
  "Бытовая техника": 3,
  Продукты: 4,
  Инструменты: 5,
  Мебель: 6,
};

const round1 = (n: number) => Math.round(n * 10) / 10;

/**
 * Собрать демо-каталог: у каждого варианта свой артикул, штрихкод и габариты.
 * `makeId` приходит снаружи (в сторе это uid), чтобы модуль не зависел от него.
 */
export function buildCatalog(makeId: () => string): Product[] {
  const out: Product[] = [];
  const counters: Record<number, number> = {};
  let barcodeSeq = 0;

  for (const m of MODELS) {
    const step = m.step ?? 0;
    const colors = m.colors ?? [null];
    m.variants.forEach((variant, i) => {
      const k = 1 + step * i;
      for (const color of colors) {
        const prefix = SKU_PREFIX[m.category];
        counters[prefix] = (counters[prefix] ?? 0) + 1;
        barcodeSeq += 1;
        out.push({
          id: makeId(),
          sku: `УК-${prefix}${String(counters[prefix]).padStart(3, "0")}`,
          barcode: toEan13(`4600051${String(barcodeSeq).padStart(5, "0")}`),
          name: [m.base, variant, color].filter(Boolean).join(", "),
          category: m.category,
          widthCm: round1(m.w * k),
          heightCm: round1(m.h * k),
          depthCm: round1(m.d * k),
          weightKg: round1(m.kg * k),
        });
      }
    });
  }
  return out;
}
