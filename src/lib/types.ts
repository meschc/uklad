/**
 * Категория товара — свободная строка: набор категорий редактируется в
 * интерфейсе и живёт в сторе (`categories`), а `PRODUCT_CATEGORIES` остаётся
 * стартовым списком для нового склада (п.15).
 */
export type ProductCategory = string;

/** Партнёр-продавец склада: чей это товар (п.15). */
export interface Partner {
  id: string;
  name: string;
  /** Контакт для связи — телефон или почта, как удобнее. */
  contact?: string;
}

/**
 * Сообщение в переписке склада с продавцом (п.3).
 *
 * Отправитель — сторона, а не человек: пользователь в прототипе один и
 * переключает роль (см. `session.slice.ts`), второго аккаунта нет. Когда
 * появится backend, `from` станет ссылкой на пользователя, а сама лента
 * переезжает в таблицу как есть — поэтому она плоская.
 *
 * `readAt` хранится у сообщения, а не счётчиком у переписки. Счётчик врёт при
 * первом же расхождении: сообщение можно удалить, можно дописать задним числом
 * при синхронизации, и «непрочитанных 3» перестаёт совпадать с лентой. Отметка
 * на самом сообщении пересчитывается всегда и не расходится ни с чем.
 */
export interface ChatMessage {
  id: string;
  /** Кто написал: склад или продавец. */
  from: UserRole;
  text: string;
  at: number;
  /** Когда другая сторона это прочитала. Пусто — ещё не прочитано. */
  readAt?: number;
}

/**
 * Товар. Обязательные атрибуты по ТЗ: артикул/SKU, штрихкод, категория,
 * фото (для демо генерируется), габариты Ш×В×Г в см с десятыми. Вес — опционально.
 */
export interface Product {
  id: string;
  sku: string;
  barcode: string;
  name: string;
  category: ProductCategory;
  widthCm: number;
  heightCm: number;
  depthCm: number;
  weightKg?: number;
  /** Ссылка на карточку товара (сайт/1С). Необязательна. */
  url?: string;
  /** Ссылка на изображение товара — показывается в карточке и таблице. */
  imageUrl?: string;
  /** Партнёр-продавец, чей это товар (`Partner.id`). */
  partnerId?: string;
}

