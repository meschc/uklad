// ---------------------------------------------------------------------------
// Модель данных прототипа «Уклад».
// Адресация места хранения (ТЗ, разд. 2.1):
//   Склад → Этаж/ряд → Секция → Полка → Ячейка
// На этом этапе (приоритет №1) реализуем уровень «Этаж → Модули (в т.ч. Секции)».
// Полки/ячейки — следующий пункт плана, но модель уже заложена совместимо.
// ---------------------------------------------------------------------------

export type ModuleType = "section" | "aisle" | "stairs" | "elevator";

/** Инструмент в левом рейле редактора. */
export type Tool = "select" | "pan" | ModuleType;

/** Экран склада: 2D-план / Таблица / 3D (ТЗ, разд. 3.5–3.7). */
export type ViewMode = "2d" | "table" | "3d";

/**
 * Размещённый на плане этажа модуль.
 * Координаты и размеры — в КЛЕТКАХ сетки (не в пикселях и не в см).
 * Сетка резиновая: x/y могут быть любыми целыми, в т.ч. отрицательными.
 */
export interface PlacedModule {
  id: string;
  type: ModuleType;
  x: number; // левый верхний угол, клетки
  y: number;
  w: number; // ширина в клетках (уже с учётом поворота)
  h: number; // высота в клетках
  rotation: 0 | 90 | 180 | 270;
  /**
   * Реальные габариты в сантиметрах — ХРАНЯТСЯ как данные, но НЕ влияют
   * на визуальный масштаб (ТЗ, разд. 2.6). Модель условная, пропорциональная.
   * Высота нужна для вывода габаритов ячейки: полки делят её пропорционально.
   */
  realWidthCm?: number;
  realDepthCm?: number;
  realHeightCm?: number;
  label?: string;
  /**
   * Собственный номер секции в адресе (ТЗ, разд. 2.1). Задаётся вручную или
   * автонумерацией и НЕ зависит от порядка создания модуля. Если не задан —
   * подставляется порядковый номер среди секций этажа (обратная совместимость).
   */
  number?: number;
  /**
   * Номер ряда, в котором стоит секция. Ряд определяется автоматически
   * (стеллажи, стоящие одной линией) и подтверждается пользователем.
   */
  row?: number;
  // Задел под следующий пункт: конфигурация полок/ячеек внутри секции.
  shelves?: ShelfConfig[];
}

/** Полка внутри секции (ТЗ, разд. 2.3). */
export interface ShelfConfig {
  id: string;
  cells: number; // 1..10 ячеек на полке (делят ширину пропорционально)
  /**
   * Собственный номер полки в адресе. Не задан — считается автоматически по
   * направлению из настроек адресации (снизу вверх / сверху вниз).
   */
  number?: number;
  /**
   * Приоритет отбора (п.10.2): чем МЕНЬШЕ число, тем ближе полка к проходу и
   * тем раньше её предложит автоподбор места. Не задан — обычная полка
   * (`DEFAULT_PICK_PRIORITY`). Ходовой товар кладут ближе, запас — выше.
   */
  pickPriority?: number;
  /**
   * Можно ли отбирать с этой полки. `false` — полка исключена из автоподбора
   * (карантин, брак, чужой товар), но лежащее на ней никуда не девается.
   * По умолчанию — можно.
   */
  pickable?: boolean;
}

/** Приоритет отбора у полки без явной настройки — середина шкалы. */
export const DEFAULT_PICK_PRIORITY = 50;
export const PICK_PRIORITY_MIN = 0;
export const PICK_PRIORITY_MAX = 99;

/**
 * Как устроена адресация на конкретном складе. Схемы у всех разные, поэтому
 * уровни адреса настраиваются, а не зашиты намертво (ТЗ, разд. 2.1).
 */
export interface AddressingConfig {
  /**
   * Участвует ли «этаж» отдельным уровнем адреса. Для складов с одним этажом
   * номер этажа избыточен. По умолчанию (и для старых данных без поля) — да.
   */
  useFloor?: boolean;
  /** Участвует ли «ряд» отдельным уровнем: этаж-ряд-секция-полка-ячейка. */
  useRows: boolean;
  /** Полка №1 — нижняя (обычно) или верхняя. */
  shelfOrder: "bottomUp" | "topDown";
  /** Разделитель уровней в строке адреса. */
  separator: string;
  /** Пользователь уже ответил на вопросы — больше не предлагаем настроить. */
  configured: boolean;
}

export const DEFAULT_ADDRESSING: AddressingConfig = {
  useFloor: true,
  useRows: false,
  shelfOrder: "bottomUp",
  separator: "-",
  configured: false,
};

/**
 * Шаблон раскладки полок/ячеек в библиотеке (ТЗ, разд. 2.3 —
 * «отдельная библиотека шаблонов, как компоненты в Figma»).
 * Хранит только раскладку (число ячеек по полкам), без привязки к секции.
 */
export interface ShelfTemplate {
  id: string;
  name: string;
  cells: number[]; // число ячеек на каждой полке, длина = число полок
}

/**
 * Один модуль в шаблоне раскладки (#38). Смещения `dx/dy` — от левого верхнего
 * угла габарита всей группы, чтобы штамп не зависел от того, где группу
 * сохранили. Полки хранятся как число ячеек по полкам (id перегенерируются при
 * штампе), по образцу ShelfTemplate.
 */
export interface LayoutModuleSpec {
  type: ModuleType;
  dx: number;
  dy: number;
  w: number;
  h: number;
  rotation?: 0 | 90 | 180 | 270;
  realWidthCm?: number;
  realDepthCm?: number;
  realHeightCm?: number;
  shelves?: number[];
}

/**
 * Шаблон раскладки модулей (#38): сохранённая группа секций/проходов/лестниц,
 * которую можно штамповать на план — как компонент в Figma, но из нескольких
 * модулей, а не из раскладки полок одной секции.
 */
export interface LayoutTemplate {
  id: string;
  name: string;
  modules: LayoutModuleSpec[];
}

