/**
 * Стороннность ряда и порядок нумерации секций внутри него.
 *
 * `sided`:
 *   - "auto" (по умолчанию) — определяем по форме: две параллельные линии
 *     секций через проход = двусторонний, одна линия = односторонний;
 *   - "two"  — двусторонний: одна сторона нечёт, другая чёт (складская классика);
 *   - "one"  — односторонний: секции нумеруются подряд.
 * `oddSide` — какая сторона получает нечётные номера (для двустороннего):
 *   "near" — ближняя (меньшая координата поперёк), "far" — дальняя.
 */
export interface RowConfig {
  number: number;
  sided?: "auto" | "one" | "two";
  oddSide?: "near" | "far";
}

/** Прямоугольник в клетках сетки — габарит ряда-кандидата. */
export interface CellRect {
  x: number;
  y: number;
  w: number;
  h: number;
}

/** Найденный по образцу ряд-кандидат: набор секций и его габарит. */
export interface RowCandidate {
  ids: string[];
  rect: CellRect;
}

/** Кандидат в предложении «продолжить ряды» с назначенным номером и галочкой. */
export interface RowProposalItem extends RowCandidate {
  number: number;
  checked: boolean;
}

/**
 * Предложение авто-продолжения рядов по образцу (ТЗ, разд. 3.5). Возникает
 * после закрепления ряда: система находит такие же по форме нераспределённые
 * группы секций и предлагает пронумеровать их подряд. Состояние временное —
 * в persist не попадает.
 */
export interface RowProposal {
  anchor: number;
  candidates: RowProposalItem[];
}

export interface Floor {
  id: string;
  name: string;
  modules: PlacedModule[];
  /**
   * Собственный номер этажа в адресе. Задаётся вручную и НЕ обязан совпадать
   * с позицией в списке: на реальном складе мезонин может быть «этажом 3»,
   * даже если он второй по порядку. Не задан — берётся позиция (совместимость
   * со старыми данными).
   */
  number?: number;
  /**
   * Конфигурация рядов этажа (стороннность, порядок нумерации). Опциональна и
   * переживает рехайдрацию: старые данные без неё работают как `sided: "auto"`.
   */
  rows?: RowConfig[];
  /**
   * Этаж-алиас (ТЗ, разд. 3.5 — тиражирование): если задан, этаж зеркалит
   * раскладку этажа-источника (обычно первого — «основного блока»). Правка
   * любого связанного этажа идёт в источник, все алиасы обновляются разом.
   * Разрыв связи материализует независимую копию. Опционально — старые данные
   * без поля остаются самостоятельными этажами.
   */
  aliasOf?: string;
}

export type WarehouseKind = "mezzanine" | "port";

/** Категория помещения по пожарной опасности (НПБ 105-03). */
export type FireCategory = "A" | "B" | "V1" | "V2" | "V3" | "V4" | "G" | "D";

/**
 * Паспорт склада — характеристики, по которым продавец выбирает подрядчика,
 * а персонал понимает ограничения работы. Ничего не вычисляется: это данные,
 * которые склад декларирует о себе.
 */
export interface WarehouseSpec {
  // --- здание ---
  /** Класс склада по общепринятой классификации (A+…D). */
  warehouseClass?: WarehouseClass;
  /** Год постройки — по нему судят о состоянии кровли, полов и проводки. */
  builtYear?: number;
  /** Общая площадь здания, м². */
  totalAreaM2?: number;
  /** Из неё под хранение, м² — разница уходит на проходы, зоны и офис. */
  storageAreaM2?: number;
  /** Полезная высота до нижнего пояса ферм, м. */
  ceilingHeightM?: number;
  /** Допустимая нагрузка на пол, кг/м². */
  floorLoadKgM2?: number;
  /** Тип пола: наливной с антипылевым покрытием, бетон, плитка. */
  floorType?: string;
  /** Тип стеллажей: фронтальные, мезонин, полочные, набивные. */
  rackType?: string;
  /** Сколько паллетомест всего — главная цифра в разговоре с клиентом. */
  palletCapacity?: number;

  // --- режим работы ---
  /** Часы приёмки/отгрузки, свободной строкой: «Пн–Пт 8:00–20:00, Сб 9:00–15:00». */
  hours?: string;
  /** Работает ли круглосуточно — влияет на планирование машин. */
  round0Clock?: boolean;
  /** Как заезжать: пропуск, ворота, ограничения по высоте/длине машины. */
  accessNote?: string;
  /** Число доков (ворот) для погрузки — сколько машин встанет одновременно. */
  docks?: number;
  /** Какие ворота: доклевеллеры, с уровня земли, тентовые. */
  dockType?: string;
  /** Высота рампы, см — по ней машина либо встаёт под разгрузку, либо нет. */
  rampHeightCm?: number;
  /** Мест на площадке под ожидающие машины. */
  parkingSpots?: number;
  /** Собственная железнодорожная ветка. */
  railSpur?: boolean;

  // --- условия хранения ---
  /** Температурный режим, °C: от и до. */
  tempMinC?: number;
  tempMaxC?: number;
  /** Влажность, %: от и до. */
  humidityMin?: number;
  humidityMax?: number;
  /** Отопление / вентиляция / холодильные камеры — что физически есть. */
  climateNote?: string;

  // --- оснащение ---
  /** Техника: ричтраки, штабелёры, гидравлические тележки. */
  equipment?: string;
  /** Учётная система склада, если она уже есть. */
  wmsName?: string;
  /** Связь и Wi-Fi: от неё зависит, будут ли работать ТСД в проходах. */
  networkNote?: string;

  // --- безопасность ---
  /** Категория помещения по пожарной опасности. */
  fireCategory?: FireCategory;
  /** Спринклеры, сигнализация, план эвакуации — состояние противопожарки. */
  fireNote?: string;
  /** Охрана и видеонаблюдение. */
  securityNote?: string;
  /** Круглосуточный пост охраны на территории. */
  guarded?: boolean;
  /** Сколько камер видеонаблюдения. */
  cctvCount?: number;
  /** Контроль доступа: карты, турникет, журнал пропусков. */
  accessControl?: string;

  // --- ограничения и состояние ---
  /** Что хранить нельзя: пищевое рядом с химией, ЛВЖ, батареи и т.п. */
  restrictions?: string;
  /** Особенности: пандус, лифт, узкие проходы, ограничение по весу на ярус. */
  features?: string;
  /** Максимальная нагрузка на ярус/полку, кг — прикладной предел. */
  maxShelfKg?: number;
  /** Состояние помещения и техники своими словами. */
  condition?: string;

  // --- документы и услуги ---
  /** Страхование груза и ответственности: страховщик и лимит. */
  insuranceNote?: string;
  /** Лицензии и разрешения: СЭЗ, пожарная декларация, алкоголь. */
  licenses?: string;
  /** Дополнительные услуги: фасовка, маркировка, фотосъёмка, возвраты. */
  services?: string;
  /** Условия договора хранения свободной строкой. */
  contractNote?: string;

  /** Когда паспорт обновляли — данные устаревают. */
  updatedAt?: number;
}

/**
 * Класс склада: общепринятая рыночная шкала. Не ГОСТ и не закон — но именно её
 * называют в первом же разговоре об аренде, поэтому в паспорте она есть.
 */
export type WarehouseClass = "A+" | "A" | "B+" | "B" | "C" | "D";

export interface Warehouse {
  id: string;
  name: string;
  kind: WarehouseKind;
  /** Физический адрес склада (ТЗ, разд. 3.2 — важно для пользователя). */
  address?: string;
  /** Координаты для карты (текст + координаты + карта). */
  lat?: number;
  lng?: number;
  /** Контакты склада: по кому звонить, если что-то не сходится по приёмке. */
  phone?: string;
  email?: string;
  /** Ответственное лицо — свободной строкой, отдельно от списка персонала. */
  contactPerson?: string;
  /** Персонал склада (кладовщики, управляющие). */
  staff?: StaffMember[];
  /** Партнёры-продавцы, чей товар лежит на складе (п.15). */
  partners?: Partner[];
  /** Ответственное лицо — карточка того же вида, что у сотрудника (п.24). */
  manager?: StaffMember;
  /**
   * Паспорт склада: то, что продавец должен знать о подрядчике ДО того, как
   * повезёт товар, — режим работы, условия хранения, пожарная безопасность,
   * ограничения. Всё опционально: склад заполняет по мере готовности.
   */
  spec?: WarehouseSpec;
  /**
   * Тариф хранения: рублей за занятую ячейку в сутки (п.10.5). Сознательно
   * узкая величина — из неё считается одна метрика «стоимость хранения», а не
   * бухгалтерия: счета и платежи в прототипе не живут.
   */
  storageRatePerCell?: number;
  floors: Floor[];
}

