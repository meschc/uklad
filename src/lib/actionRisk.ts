/**
 * Классы опасности действий — одни на весь Уклад (Кирилл, 12 ноя 2026:
 * «разделить действия на списки с доступом и уровнем опасности, и возможность
 * отменить действие в течение некоторого времени»).
 *
 * - `safe` — ничего не теряется: открыть, отфильтровать, напечатать.
 * - `undoable` — убирает запись, но её можно вернуть: удалить партнёра, свою
 *   услугу, реплику. Делается сразу, без вопроса, а в тосте `UNDO_WINDOW_MS`
 *   висит «Отменить». Вопрос «вы уверены?» на каждое удаление приучает жать
 *   «да» не читая — отмена после дела честнее.
 * - `confirm` — меняет учёт или деньги: провести приёмку, закрыть рейс,
 *   выставить счёт. Подтверждение в панели справа с тем, что изменится.
 * - `irreversible` — назад не вернуть даже сервером: удалить компанию,
 *   отправить документ наружу. Подтверждение вводом названия; только
 *   руководитель.
 *
 * Доступ задаёт роль (`lib/permModules`), класс — только как переспросить.
 * Список действий по классам — `docs/design/DESIGN-SYSTEM.md`, «Опасные действия».
 */
/** Сколько висит «Отменить» после действия класса `undoable`. */
export const UNDO_WINDOW_MS = 8000;
