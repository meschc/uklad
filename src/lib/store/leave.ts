import { removeLocal } from "../safeStorage";
import { PERSIST_KEY } from "./index";

/**
 * Конец входа через сервер: выход, истёкшая или отозванная сессия.
 *
 * Данные кабинета пока лежат в браузере под одним ключом. С настоящими
 * аккаунтами это риск общего компьютера: вышел А, вошёл Б — и видит склад А.
 * Поэтому конец серверной сессии стирает сохранение целиком и открывает вход
 * с чистого листа. Перезагрузка, а не сброс стора на месте: посев живёт в
 * одном месте — на старте приложения (как «Демо-данные → Загрузить заново»).
 *
 * `offline` — выход не дошёл до сервера: на этом устройстве человек вышел,
 * а сессия на сервере ещё жива. Экран входа скажет об этом прямо.
 */
export function leaveServerSession(note?: "offline") {
  removeLocal(PERSIST_KEY);
  const query = note ? "?view=login&logout=offline" : "?view=login";
  window.location.replace(`${window.location.pathname}${query}`);
}
