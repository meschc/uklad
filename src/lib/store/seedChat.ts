/** Реплика по счётчику — чтобы подряд не приходило одно и то же. */
export function demoReplyFor(from: ChatMessage["from"], seed: number): string {
  const pool = DEMO_REPLIES[from];
  return pool[seed % pool.length];
}

/** Разложить сценарии по первым партнёрам склада. */
export function seedChatFor(partners: Partner[]): Record<string, ChatMessage[]> {
  const now = nowMs();
  const chats: Record<string, ChatMessage[]> = {};

  partners.slice(0, SCRIPTS.length).forEach((partner, i) => {
    chats[partner.id] = SCRIPTS[i].map((line) => ({
      id: uid("msg"),
      from: line.from,
      text: line.text,
      at: now - line.ago,
      // Прочитанным считаем всё, кроме последней реплики продавца: она и есть
      // то новое, ради чего человек в чат заходит.
      readAt: line.from === "warehouse" ? now - line.ago + MINUTE : undefined,
    }));

    // Ответы склада продавец давно прочитал; непрочитанным у него ничего не
    // остаётся — иначе счётчик горел бы у обеих сторон сразу и ничего не значил.
    const messages = chats[partner.id];
    for (let k = 0; k < messages.length - 1; k += 1) {
      if (!messages[k].readAt) messages[k] = { ...messages[k], readAt: messages[k].at + MINUTE };
    }
  });

  return chats;
}
