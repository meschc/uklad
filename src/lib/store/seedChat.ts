/**
 * Демо-переписка склада с продавцами (п.3).
 *
 * Раздаётся один раз при первом открытии чата и по живым партнёрам склада —
 * не при сборке стора. Причина простая: у сохранённого склада партнёры свои, а
 * заготовленные заранее ленты ссылались бы на id, сгенерированные при загрузке
 * модуля, и чат открывался бы пустым с непрочитанными сообщениями «в никуда».
 *
 * Разговоры взяты не из головы: это то, из-за чего склад и продавец пишут друг
 * другу на самом деле — окно приёмки, недостача, тариф, возврат. Пустой чат в
 * демо не показывает ничего, а чат с «привет / привет» — что продукт игрушка.
 */

const MINUTE = 60_000;

/** Реплика сценария: кто, что и когда написал. */
interface Line {
  from: ChatMessage["from"];
  text: string;
  /**
   * Сколько суток назад и во сколько по часам. Именно время на часах, а не
   * «столько-то часов назад»: иначе реплики ложатся ровно на 16:04, 17:04,
   * 18:04, а «машина ушла в 14:20» оказывается написана в шесть вечера —
   * демо выглядит сгенерированным. Все реплики не позже вчерашнего дня, чтобы
   * ни одна не оказалась в будущем при раннем открытии кабинета.
   */
  when: [days: number, time: string];
}

