import type { MsgKey } from "../i18n";

/**
 * Один конверт ответа для всего слоя данных (п.3.2.2).
 *
 * Сегодня действие стора не умеет проваливаться: `set()` всегда успешен,
 * поэтому в экранах нет ни ожидания, ни ошибки. Сеть так себя не ведёт — и
 * когда за репозиторием появится `fetch`, отсутствие ветки «не вышло» означало
 * бы переписывание каждого обработчика. Конверт вводится заранее, пока
 * обработчиков полтора десятка, а не полсотни.
 *
 * Ошибка — это ключ словаря, а не строка сервера. Интерфейс двуязычный:
 * сырую фразу из ответа показать нельзя, её нечем перевести. Подробности
 * ответа место в консоли, а не на экране, — их пишет `attempt`.
 */
export type Result<T> = { ok: true; data: T } | { ok: false; error: MsgKey };

export function ok<T>(data: T): Result<T> {
  return { ok: true, data };
}

export function fail(error: MsgKey): Result<never> {
  return { ok: false, error };
}

/**
 * Выполнить операцию и вернуть её в конверте. Единственное место, где
 * исключение превращается в ответ: репозитории не пишут `try` каждый по-своему,
 * а экран получает предсказуемую форму независимо от того, что упало —
 * повреждённый `localStorage`, сбойный запрос или ошибка в самом действии.
 */
export async function attempt<T>(
  run: () => Promise<T> | T,
  error: MsgKey = "data.failed",
): Promise<Result<T>> {
  try {
    return ok(await run());
  } catch (e) {
    console.error("[uklad] операция не выполнена:", e);
    return fail(error);
  }
}
