import qrcode from "qrcode-generator";

/**
 * QR-код (п.5). На складе печатается и клеится ровно один тип кода — QR:
 *
 *  — он двумерный, поэтому при том же размере ярлыка держит больше символов и
 *    остаётся читаемым с ободранного и мятого короба (встроенная коррекция
 *    ошибок восстанавливает до четверти площади);
 *  — его читает камера телефона, а не только «пистолет»: приёмку можно вести
 *    тем, что уже есть в кармане у кладовщика;
 *  — он квадратный, а значит одинаково хорошо ложится и на узкую полочную
 *    планку, и на торец короба — линейному коду для этого нужна ширина.
 *
 * Кодирование не своё: `qrcode-generator` — эталонная реализация Кадзухико
 * Арасэ, 3 КБ, без зависимостей. Свой энкодер здесь означал бы Рида—Соломона и
 * восемь масок ради того же результата.
 */

/** Уровень коррекции ошибок: L 7% · M 15% · Q 25% · H 30% площади. */
export type QrEcc = "L" | "M" | "Q" | "H";

/**
 * Байты строки — в UTF-8. Библиотека по умолчанию берёт `charCodeAt(i) & 0xff`,
 * то есть режет всё за пределами латиницы: «УК-BOX-000123» уехал бы в QR как
 * «#R-BOX-000123» и после скана не нашёлся бы ни в одной коробке. Наши номера
 * тары начинаются с кириллицы, поэтому подменяем кодировщик один раз на модуль.
 */
qrcode.stringToBytes = (s: string): number[] => [...new TextEncoder().encode(s)];

/**
 * Матрица модулей QR: `true` — чёрный. Версия 0 = «подобрать минимальную под
 * длину строки», так и оставляем: наши коды короткие, лишние модули только
 * мельчат печать.
 */
export function qrMatrix(value: string, ecc: QrEcc = "M"): boolean[][] {
  const qr = qrcode(0, ecc);
  qr.addData(value);
  qr.make();
  const n = qr.getModuleCount();
  const rows: boolean[][] = [];
  for (let r = 0; r < n; r++) {
    const row: boolean[] = [];
    for (let c = 0; c < n; c++) row.push(qr.isDark(r, c));
    rows.push(row);
  }
  return rows;
}

/**
 * Путь SVG из матрицы — один `<path>` вместо сотен `<rect>`. Для ярлыка на
 * 25×25 модулей это разница между 600 узлами DOM и одним: на печати пачки в
 * сотню наклеек она видна невооружённым глазом.
 */
export function qrPath(matrix: boolean[][]): string {
  const parts: string[] = [];
  for (let r = 0; r < matrix.length; r++) {
    for (let c = 0; c < matrix[r].length; c++) {
      if (matrix[r][c]) parts.push(`M${c} ${r}h1v1h-1z`);
    }
  }
  return parts.join("");
}

