/**
 * Локальное хранилище, которое не роняет страницу.
 *
 * Обращение к `localStorage` — не безобидное чтение поля. В приватном окне
 * Safari и при запрете хранилища в настройках браузера оно бросает исключение,
 * а при сборке страниц в статику этой переменной нет вовсе: код выполняется в
 * Node. Необёрнутый вызов в обработчике кнопки означает, что кнопка молча
 * перестаёт работать у части людей, и понять это по интерфейсу нельзя.
 *
 * Раньше защита писалась по месту: четыре файла, четыре одинаковых `try` и
 * четыре объяснения, почему он здесь. Теперь объяснение одно — вот это.
 *
 * Правило простое: **хранилище может не сработать, и это нормально.** Чтение
 * возвращает `null`, запись и удаление молчат. Ничего важного здесь не лежит:
 * язык витрины, свёрнутые секции панели, выбор в баннере cookie. Всё это в
 * текущей вкладке применится и без записи — не переживёт только её закрытия.
 * Данные, потеря которых заметна (сам склад), пишет `persist` стора, и там
 * своя обработка сбоя.
 */

/** Значение по ключу или `null` — в том числе когда хранилище недоступно. */
export function readLocal(key: string): string | null {
  try {
    return localStorage.getItem(key);
  } catch {
    return null;
  }
}

/** Записать значение. Сбой хранилища не считается ошибкой приложения. */
export function writeLocal(key: string, value: string): void {
  try {
    localStorage.setItem(key, value);
  } catch {
    /* приватный режим или запрет хранилища — просто не запоминаем */
  }
}

/** Удалить значение. Молчит по той же причине, что и запись. */
export function removeLocal(key: string): void {
  try {
    localStorage.removeItem(key);
  } catch {
    /* нечего удалять или хранилище недоступно */
  }
}

/** Есть ли запись по ключу. Недоступное хранилище — это «нет». */
export function hasLocal(key: string): boolean {
  return readLocal(key) != null;
}
