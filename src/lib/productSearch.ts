import type { Product } from "./types";

/**
 * Поиск по номенклатуре.
 *
 * Один ответ на вопрос «подходит ли товар под запрос» для двух мест, которые
 * ищут по одному и тому же складу: таблица товаров и набор заявки на отгрузку.
 * До этого предикат был написан дважды и успел разойтись — таблица искала ещё
 * и по категории, заявка нет, — хотя человек, набирающий заявку, ждёт от поиска
 * ровно того же, что и в таблице. Теперь расходиться нечему.
 */

/**
 * Привести запрос к виду, в котором с ним сравнивают. Отдельной функцией,
 * потому что `trim` здесь не косметика: «молоко » с хвостовым пробелом не
 * находит ничего, и по экрану не видно почему.
 */
export function normalizeQuery(raw: string): string {
  return raw.trim().toLowerCase();
}

/**
 * Подходит ли товар под уже нормализованный запрос. Пустой запрос подходит
 * всему: «ничего не искали» — это «покажи всё», а не «не нашлось ничего».
 *
 * @param place адрес хранения, если вызывающий его знает: таблица знает, набор
 *   заявки — нет. Искать по адресу нужно затем же, зачем по артикулу, — «что
 *   лежит на 1-2-3» обычный складской вопрос.
 */
export function matchesQuery(product: Product, query: string, place?: string | null): boolean {
  if (!query) return true;
  return (
    product.name.toLowerCase().includes(query) ||
    product.sku.toLowerCase().includes(query) ||
    // Штрихкод — цифры, регистр ему безразличен.
    product.barcode.includes(query) ||
    product.category.toLowerCase().includes(query) ||
    (place ?? "").includes(query)
  );
}
