import { clsx, type ClassValue } from "clsx";
import { twMerge } from "tailwind-merge";

export function cn(...inputs: ClassValue[]) {
  return twMerge(clsx(inputs));
}

/** Ограничить число диапазоном [min, max]. */
export function clamp(value: number, min: number, max: number) {
  return Math.min(max, Math.max(min, value));
}

/**
 * Случайный UUID. Отдельная функция, а не вызов `crypto.randomUUID()` на месте:
 * браузер даёт `crypto` только в защищённом контексте — по https и на
 * localhost. По http со стенда в локальной сети его нет, и приложение упало бы
 * на создании первой же коробки. Запасной путь собирает тот же формат из
 * `getRandomValues`, последний — из `Math.random`, чтобы не остаться без id
 * вовсе.
 */
function randomUuid(): string {
  const c = globalThis.crypto;
  if (c?.randomUUID) return c.randomUUID();

  const bytes = new Uint8Array(16);
  if (c?.getRandomValues) c.getRandomValues(bytes);
  else for (let i = 0; i < 16; i++) bytes[i] = Math.floor(Math.random() * 256);

  bytes[6] = (bytes[6] & 0x0f) | 0x40; // версия 4
  bytes[8] = (bytes[8] & 0x3f) | 0x80; // вариант RFC 4122
  const hex = Array.from(bytes, (b) => b.toString(16).padStart(2, "0")).join("");
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20)}`;
}

/**
 * Идентификатор сущности. Ставит его клиент — иначе интерфейс ждал бы ответа
 * сервера, чтобы нарисовать только что созданную коробку.
 *
 * Когда появится бэкенд, этот id останется временным: репозиторий отправляет
 * запись с ним, а в ответе получает серверный и подменяет (оптимистичное
 * обновление). Поэтому здесь UUID, а не семь случайных символов, как было в
 * прототипе: временные id живут в одних списках с серверными, и совпадение
 * здесь — не «редкая неудача», а молча перезаписанная чужая строка.
 *
 * Префикс остаётся: по нему видно в логе и в localStorage, что это за запись.
 */
export function uid(prefix = "id") {
  return `${prefix}_${randomUuid()}`;
}

/**
 * Текущее время, миллисекунды. Один вход вместо `Date.now()` по коду: когда
 * появится сервер, расхождение часов клиента и сервера чинится здесь, а не в
 * двадцати срезах, и тестам есть куда подставить управляемые часы.
 *
 * Имя с суффиксом намеренно: в коде уже есть места, где `now` — это снимок
 * момента операции (`const now = nowMs()`, параметр-часы у `buildPickDoc`).
 * Одноимённая функция затеняла бы их и ломала бы собственные значения по
 * умолчанию (`function f(now = now())`).
 */
export function nowMs(): number {
  return Date.now();
}

/**
 * Стабильная пустая ссылка для селекторов стора: `s.x ?? []` возвращал бы новый
 * массив на каждый рендер, и подписка считала бы состояние изменившимся.
 */
export const EMPTY_ARRAY: never[] = [];

/**
 * Метка порядка байтов, U+FEFF. Excel открывает CSV без неё в однобайтовой
 * кодировке, и кириллица приезжает кракозябрами; с ней — читает как UTF-8.
 * Ставится в начало выгрузки и срезается на входе при импорте.
 *
 * Собрана из кода, а не написана символом: сам знак невидим, и в исходнике его
 * ничего не стоит случайно затереть или продублировать, не заметив пропажи.
 * Имя в коде видно, невидимый пробел — нет.
 */
export const BOM = String.fromCharCode(0xfeff);
