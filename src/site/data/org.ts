/**
 * Реквизиты владельца сайта — единственное место, где они лежат.
 *
 * Их требуют сразу три закона: ст. 10 149-ФЗ (наименование, адрес, почта на
 * сайте), ст. 9 закона «О защите прав потребителей» (фирменное наименование и
 * режим работы) и ст. 18.1 152-ФЗ (сведения об операторе в политике). Поэтому
 * одни и те же строки печатаются на пяти страницах — и меняться должны в одной.
 *
 * Значения здесь — демонстрационные, и подобраны так, что совпасть с живой
 * компанией не могут в принципе. Случайные цифры для этого не годятся: они как
 * раз попадают в чей-нибудь настоящий ИНН. Поэтому каждое число нарушает
 * правило, по которому его выдают, — и не одно, а сразу два:
 *
 * - ИНН `0077250195`: первые две цифры ИНН — код субъекта РФ, кода `00` не
 *   существует; вдобавок контрольная цифра не сходится (по весам
 *   2-4-10-3-5-9-4-6-8 должна быть 4).
 * - ОГРН `0220008456191`: первая цифра — признак отнесения, юрлицу выдают 1, 2
 *   или 5, ноль не выдают никогда; регион снова `00`, и контрольный разряд
 *   не совпадает с остатком от деления на 11 (должен быть 5).
 * - КПП `007701001`: первые четыре цифры — код налогового органа, он начинается
 *   с кода региона, а `00` его не имеет.
 * - Индекс `009160`: почтовые индексы России начинаются с цифр 1–6.
 * - Телефон `+7 (200) …`: коды 2xx в российском плане нумерации не выделены —
 *   ABC-коды начинаются с 3, 4 и 8, DEF-коды с 9.
 * - Домен `uklad.example`: зона `.example` зарезервирована RFC 2606 и не может
 *   быть кем-либо зарегистрирована.
 *
 * Любая проверка — по контрольной сумме, по ЕГРЮЛ, по whois — отвергнет их
 * сразу. Поэтому `filled` остаётся false: подвал добавляет к своей оговорке
 * полстроки о том, что реквизиты учебные. Подставите настоящие — поднимите
 * флаг, и полстроки исчезнут.
 */
export interface Org {
  /** Подставлены ли настоящие реквизиты вместо заглушек. */
  filled: boolean;
  /** Полное фирменное наименование — как в ЕГРЮЛ. */
  legalName: string;
  /** Короткое имя для текста документов. */
  shortName: string;
  inn: string;
  ogrn: string;
  kpp: string;
  /** Юридический адрес (место нахождения). */
  address: string;
  /** Кто подписывает документы — нужен в оферте. */
  director: string;
  email: string;
  /** Отдельный ящик для обращений по персональным данным (ст. 14 152-ФЗ). */
  privacyEmail: string;
  phone: string;
  /** Режим работы поддержки. */
  hours: string;
  site: string;
  /** Номер в реестре операторов ПДн Роскомнадзора, если уведомление подано. */
  rknNumber?: string;
}

