/**
 * Реквизиты владельца сайта — единственное место, где они лежат.
 *
 * Владелец — индивидуальный предприниматель, а не общество. Разница не
 * косметическая: у ИП нет фирменного наименования (есть ФИО), нет КПП вовсе,
 * вместо ОГРН выдаётся пятнадцатизначный ОГРНИП, ИНН двенадцатизначный, а
 * выписку дают из ЕГРИП. Всё это печатается на правовых страницах дословно,
 * поэтому подмена одного слова в подвале ничего бы не решила.
 *
 * Их требуют сразу три закона: ст. 10 149-ФЗ (для индивидуального
 * предпринимателя — ФИО и адрес электронной почты), ст. 9 закона «О защите
 * прав потребителей» (наименование и режим работы) и ст. 18.1 152-ФЗ (сведения
 * об операторе в политике). Поэтому одни и те же строки печатаются на пяти
 * страницах — и меняться должны в одной.
 *
 * Значения здесь — демонстрационные, и подобраны так, что совпасть с живым
 * предпринимателем не могут в принципе. Случайные цифры для этого не годятся:
 * они как раз попадают в чей-нибудь настоящий ИНН. Поэтому каждое число
 * нарушает правило, по которому его выдают, — и не одно, а сразу два:
 *
 * - ИНН `007725019512`: первые две цифры ИНН — код субъекта РФ, кода `00` не
 *   существует; вдобавок оба контрольных разряда не сходятся (должны быть 7 и 6).
 * - ОГРНИП `002000845619109`: первая цифра — признак отнесения, предпринимателю
 *   выдают 3 (иностранцу 4), ноль не выдают никогда; регион снова `00`, и
 *   контрольный разряд не совпадает с остатком от деления первых четырнадцати
 *   цифр на 13 (должен быть 2).
 * - Индекс `009160`: почтовые индексы России начинаются с цифр 1–6.
 * - Телефон `+7 (200) …`: коды 2xx в российском плане нумерации не выделены —
 *   ABC-коды начинаются с 3, 4 и 8, DEF-коды с 9.
 *
 * Любая проверка — по контрольной сумме, по ЕГРИП, по whois — отвергнет их
 * сразу. Поэтому `filled` остаётся false: подвал добавляет к своей оговорке
 * полстроки о том, что реквизиты учебные. Подставите настоящие — поднимите
 * флаг, и полстроки исчезнут.
 *
 * Домен из этого списка выбыл: `u-klad.ru` зарегистрирован 13 сентября 2026 на
 * владельца сайта и настоящий — в отличие от всего остального здесь. Иначе и
 * нельзя: от него считаются canonical, hreflang и карта сайта, а заглушка в
 * них — это не «пока не решили», а прямая ошибка в выдаче. Почтовые ящики
 * `hello@` и `privacy@` на этом домене должны существовать на самом деле:
 * пока приёмник форм не настроен, письмо уходит через `mailto:`, и на
 * несуществующий ящик оно просто пропадёт.
 */
import { c, type Copy } from "../lib/copy";

export interface Org {
  /** Подставлены ли настоящие реквизиты вместо заглушек. */
  filled: boolean;
  /** Полное наименование — как в ЕГРИП: «Индивидуальный предприниматель» и ФИО. */
  legalName: string;
  /** Короткое имя для текста документов. */
  shortName: string;
  /** ИНН предпринимателя — двенадцать цифр, в отличие от десяти у юрлица. */
  inn: string;
  /** ОГРНИП — пятнадцать цифр. КПП у предпринимателя не бывает вовсе. */
  ogrnip: string;
  /** Адрес для корреспонденции: адрес регистрации ИП по закону раскрывать не нужно. */
  address: string;
  /** Кто подписывает документы. У ИП это он сам — доверенность не нужна. */
  director: string;
  email: string;
  /** Отдельный ящик для обращений по персональным данным (ст. 14 152-ФЗ). */
  privacyEmail: string;
  phone: string;
  /**
   * Режим работы поддержки — единственное поле здесь на двух языках.
   *
   * Остальные реквизиты одноязычны не по недосмотру: имя предпринимателя, адрес
   * и номера в реестрах имеют силу ровно в том виде, в каком записаны в ЕГРИП,
   * и перевод их не улучшит, а испортит. Режим работы — не реквизит из реестра,
   * а ответ на вопрос «когда вам ответят», и на английской версии он должен
   * читаться по-английски. В правовые документы уходит русская половина.
   */
  hours: Copy;
  site: string;
  /** Номер в реестре операторов ПДн Роскомнадзора, если уведомление подано. */
  rknNumber?: string;
}

