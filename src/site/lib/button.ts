import { cn } from "@/lib/utils";

/**
 * Кнопка витрины — размер и тон, больше ничего.
 *
 * До этого файла кнопок как сущности не было вовсе: сорок с лишним `<button>` и
 * ссылок-кнопок, набранных каждая по месту. Высот набралось девять — 32, 36, 40,
 * 44, 48, отдельно `h-[52px]` у двух главных кнопок первого экрана, и ещё три
 * штуки, у которых высоты нет совсем, а есть `py-1`, `py-1.5`, `py-2`. Рамка
 * жила в двух наборах в одной роли: `border-border` с `hover:bg-muted` —
 * кабинетный, случайно приехавший в сборку витрины, и `border-stroke` с
 * `hover:border-stroke-hover hover:bg-wash` — её собственный. Главный призыв
 * был скопирован двадцать раз и успел разъехаться: `h-11 px-5 text-sm` и
 * `h-12 px-7 text-base` стояли в одной и той же роли на разных страницах.
 *
 * Ступеней высоты три, и это тот же приём, что и в кабинете («одна высота на
 * строку интерфейса»), только числа свои: витрина крупнее, у неё есть первый
 * экран, которому нужен призыв заметного размера, а у кабинета такого места
 * нет. Нижняя ступень совпадает намеренно — 32 px это предел, ниже которого
 * палец на телефоне промахивается.
 *
 * Форма — классы, а не компонент, как у [`eyebrow`](./eyebrow.ts) и у карточки
 * в кабинете. Кнопкой на витрине бывает и `<button>`, и `<a>` (переход на
 * страницу — это ссылка, и она обязана открываться в новой вкладке по
 * Cmd-клику), и `<label>` у скрытого поля. Оборачивать это в один тег значило
 * бы ломать разметку и доступность ради вида.
 *
 *   <a className={siteButton({ size: "lg" })}>Подобрать склад</a>
 *   <button className={siteButton({ tone: "outline" })}>Сбросить</button>
 *   <button className={siteButton({ size: "sm", tone: "ghost", className: "lg:hidden" })}>
 *
 * Раскладка вокруг — `w-full`, `mt-6`, `flex-1`, `lg:hidden` — остаётся на
 * месте вызова: это про положение кнопки на странице, а не про саму кнопку.
 * `cn` внутри — это `tailwind-merge`, поэтому `className` умеет перебить и то,
 * что пришло из варианта: у двух кнопок первого экрана внутри кружок со
 * стрелкой, и им нужен свой `justify-between` вместо общего `justify-center`.
 */

const BASE =
  "inline-flex items-center justify-center gap-2 rounded-full font-medium " +
  "transition-colors disabled:pointer-events-none disabled:opacity-40";

/**
 * Высота, поля и кегль ходят вместе. Порознь они и разъехались: кто-то менял
 * высоту, не трогая поля, и кнопка становилась то приплюснутой, то пустой
 * внутри. Кегль здесь — ступень шкалы, а не число.
 */
const SIZE = {
  /** 32 px — служебные: переключатель языка, «показать ещё», кнопка в карточке. */
  sm: "h-8 px-3.5 text-xs",
  /** 40 px — по умолчанию: формы, вторичные действия, кнопки в каталоге. */
  md: "h-10 px-5 text-sm",
  /** 48 px — главный призыв: первый экран, финальный блок, конец страницы. */
  lg: "h-12 px-7 text-base",
} as const;

/**
 * Тон — насколько громко кнопка просит нажать. Рамка и фон взяты из токенов
 * витрины (`--stroke`, `--wash`), а не из кабинетных `border`/`muted`: у витрины
 * темнее фон, и кабинетная рамка на нём читается как грязь по краю.
 */
const TONE = {
  /** Заливка. На экране их должно быть по одной: две главные кнопки — ни одной. */
  primary: "bg-primary text-primary-foreground hover:bg-primary/90",
  /** Рамка — рядом с заливкой или вместо неё там, где выбор равноправный. */
  outline: "border border-stroke text-foreground hover:border-stroke-hover hover:bg-wash",
  /** Без рамки — действие служебное и не должно спорить с содержимым страницы. */
  ghost: "text-muted-foreground hover:bg-wash hover:text-foreground",
} as const;

export function siteButton({
  size = "md",
  tone = "primary",
  className,
}: {
  size?: keyof typeof SIZE;
  tone?: keyof typeof TONE;
  className?: string;
} = {}): string {
  return cn(BASE, SIZE[size], TONE[tone], className);
}

/**
 * Пилюля в пилюле — главный призыв первого экрана и финального блока.
 *
 * Вариантом `siteButton` она не стала намеренно: у обычной кнопки содержимое
 * стоит по центру, а здесь оно разъезжается по краям, потому что справа внутри
 * сидит кружок со стрелкой. Это не «кнопка потемнее», а другая форма, и
 * подмешивать её третьим тоном значило бы описывать словом «тон» разметку.
 *
 * Поэтому отдельная функция — но одна на оба места. Автор первого экрана уже
 * написал в комментарии, что «два конца страницы держит одна форма»; на деле
 * копии успели разойтись — на первом экране кегль был `text-sm`, в финале
 * `text-base`, поле слева 6 против 7. Общая функция и есть то, о чём тот
 * комментарий говорил.
 *
 * Высота — ступень `lg` (48), а была `h-[52px]`, мимо любой шкалы. Кружок
 * внутри остаётся 40: при поле справа в 6 px он встаёт по центру сам.
 *
 * `justify-between sm:justify-start` — про мобильную ширину: на телефоне кнопка
 * во всю строку, и кружок уезжает к правому краю; со `sm` она сжимается по
 * содержимому, и `between` от `start` уже не отличить. В финале стояло
 * `justify-center` — на широком экране это то же самое, а на телефоне кружок
 * прилипал к тексту посреди пустой кнопки.
 *
 *   <a className={ctaPill("w-full sm:w-auto")}>Подобрать склад<span …/></a>
 */
export function ctaPill(className?: string): string {
  return cn(
    "group inline-flex h-12 items-center justify-between gap-4 rounded-full sm:justify-start",
    "bg-foreground pl-7 pr-1.5 text-base font-medium text-background",
    // Движение, а не покраска: заливка у кнопки уже максимально контрастная,
    // и подсвечивать её некуда — поэтому она приподнимается.
    "transition-transform hover:-translate-y-px active:translate-y-0",
    className,
  );
}
