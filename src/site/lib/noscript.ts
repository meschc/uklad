import type { SiteLang } from "./lang";

/**
 * Перевод блока «здесь нужен JavaScript» для английских страниц.
 *
 * Блок лежит в `index.html` — в разметке, до всякого выбора языка. Увидит его
 * ровно тот, у кого скрипты не выполнились, а значит, спросить язык уже не у
 * кого: ни памяти браузера, ни переключателя в шапке в этот момент нет. На
 * `/en/` это означало русский текст перед человеком, который по-русски не
 * читает, — ровно там, где объяснение нужнее всего.
 *
 * Переводим слова, а не блок целиком. Разметка со встроенными стилями остаётся
 * в одном месте — в `index.html` (стили там встроенные не от лени: без скриптов
 * в деве таблица стилей не приезжает вовсе, и блок остался бы голым текстом).
 * Держать её копию здесь значило бы править оформление в двух файлах и однажды
 * забыть про второй.
 *
 * Не нашлась хоть одна фраза — сборка падает. Русский `<noscript>` на
 * английской странице ничем себя не выдаёт: он показывается только при
 * выключенных скриптах, то есть никогда не попадается ни на экране
 * разработчика, ни в сквозных тестах. Такое ловится либо на сборке, либо на
 * живом сайте.
 */

/** Фразы шаблона и их английские замены — в порядке появления в разметке. */
const PHRASES: readonly (readonly [ru: string, en: string])[] = [
  ["Здесь нужен JavaScript", "This page needs JavaScript"],
  [
    "Витрина складов, фильтры и карта работают скриптами. Включите JavaScript или отключите блокировщик для этого сайта — и страница откроется.",
    "Warehouse listings, filters and the map are drawn by scripts. Turn JavaScript on or allow this site in your blocker, and the page will open.",
  ],
  ["Если проще написать:", "Easier to write:"],
];

const NOSCRIPT_RE = /<noscript>[\s\S]*?<\/noscript>/;

/** Экранирование для куска, который идёт в регулярное выражение как есть. */
function escapeRe(text: string): string {
  return text.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

/**
 * Выражение по фразе, безразличное к переносам строк.
 *
 * В разметке абзац разложен по строкам как удобно Prettier, и точное совпадение
 * сломалось бы от переформатирования файла — то есть от правки, которая текста
 * не касалась. Любой пробельный промежуток между словами считаем одним пробелом.
 */
function phraseRe(text: string): RegExp {
  return new RegExp(text.split(/\s+/).map(escapeRe).join("\\s+"));
}

/**
 * Возвращает разметку страницы с переведённым `<noscript>`.
 *
 * Для русской страницы — та же строка без единого изменения: перевод обязан
 * быть заметен только там, где он нужен.
 */
export function translateNoscript(html: string, lang: SiteLang): string {
  if (lang !== "en") return html;

  const found = NOSCRIPT_RE.exec(html);
  if (!found) throw new Error("в шаблоне страницы нет блока <noscript>");

  const translated = PHRASES.reduce((text, [ru, en]) => {
    const re = phraseRe(ru);
    if (!re.test(text)) throw new Error(`в блоке <noscript> нет фразы: ${ru}`);
    return text.replace(re, en);
  }, found[0]);

  // Замена функцией, а не строкой: в тексте замены `$&` и `$1` — обычные знаки,
  // и подставлять вместо них куски совпадения незачем.
  return html.replace(NOSCRIPT_RE, () => translated);
}
