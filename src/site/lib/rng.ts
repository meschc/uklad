/**
 * Детерминированный генератор для демонстрационных данных витрины.
 *
 * Лежит отдельным файлом не ради красоты: генераторов на витрине два — склады
 * (`data/warehouses.ts`) и сделки с отзывами (`data/deals.ts`), — и оба обязаны
 * считать одинаково. Вторая копия `mulberry32`, разошедшаяся на одну строку,
 * дала бы наборы, которые невозможно связать между собой и нельзя воспроизвести
 * по описанию.
 *
 * Главное свойство, ради которого всё это существует: набор собирается один раз
 * при сборке, а не заново на каждой перезагрузке. Селлер возвращается по ссылке
 * и находит тот же склад с тем же прайсом, а не новый.
 */

/** Быстрый детерминированный ГПСЧ (mulberry32). */
export function rng(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** Целое из отрезка `min…max` включительно. Один бросок. */
export const int = (r: () => number, min: number, max: number): number =>
  min + Math.floor(r() * (max - min + 1));

/** Элемент списка. Один бросок. */
export function pick<T>(list: readonly T[], r: () => number): T {
  return list[Math.floor(r() * list.length)];
}
