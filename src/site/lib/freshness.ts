import { daysSince } from "./date";

/**
 * Свежесть данных склада: когда он в последний раз подтверждал тарифы и
 * свободные места.
 *
 * Каталог, который однажды наполнили и бросили, вредит сильнее, чем пустой:
 * селлер выбирает склад по цене, пишет заявку, и через два дня узнаёт, что цена
 * той весны, а мест нет с лета. Отличить живой профиль от брошенного он при
 * этом не мог — оба выглядели одинаково. Поэтому дата подтверждения становится
 * частью карточки, а не служебным полем в базе.
 *
 * Склад, работающий на Укладе, ничего не подтверждает руками: и остатки, и
 * прайс витрина берёт из его же системы. Это третье состояние, а не «очень
 * свежее»: у него другая природа и о ней честнее сказать прямо.
 */

/** Дольше этого срока без подтверждения — данные считаются несвежими. */
export const STALE_DAYS = 90;

export type Freshness = "live" | "fresh" | "stale";

/**
 * `live` — цифры идут из системы склада; `fresh` — склад подтверждал их не
 * дольше `STALE_DAYS` назад; `stale` — дольше.
 *
 * Порог один, а не шкала из пяти оттенков: селлеру нужно решение «доверять
 * этим числам или переспросить», и градация «свежо / почти свежо / скорее
 * несвежо» на него не влияет, зато требует объяснения.
 */
export function freshness(confirmedAt: number, now: number, live: boolean): Freshness {
  if (live) return "live";
  return daysSince(confirmedAt, now) > STALE_DAYS ? "stale" : "fresh";
}
