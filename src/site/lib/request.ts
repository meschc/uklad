import { EMPTY_VOLUME, isVolumeSet, type SellerVolume } from "./estimate";

/**
 * Заявка складу — то немногое, что склад обязан узнать до ответа.
 *
 * Раньше заявка была одной кнопкой: человек нажимал «Отправить», склад получал
 * имя и тишину — и первым же письмом спрашивал объём, товар и сроки. То есть
 * переписка начиналась не с ответа, а с анкеты, и ответ «возьмём, вот условия»
 * приходил через сутки вместо часа, который обещан на витрине.
 *
 * Полей ровно четыре, и каждое склад всё равно спросит: что за товар, сколько
 * его, когда везти и откуда. Ничего сверх — ни оборота, ни ИНН, ни ссылки на
 * магазин: это данные, которыми торгуются в договоре, а не в заявке, и
 * спрашивать их до ответа склада незачем.
 *
 * Объём — не отдельные поля заявки, а тот же `SellerVolume`, который считает
 * калькулятор витрины. Если бы заявка спрашивала своими словами («сколько
 * паллет?»), селлер сравнивал бы склады по одному числу, а склад отвечал бы по
 * другому, и разошлись бы они молча — оба уверены, что говорят об одном.
 *
 * Отправлять пока некуда: витрина работает на данных в браузере. Когда
 * появится бекенд, отправка добавится в одном месте — в `RequestForm`, — а
 * `RequestDraft` уже и есть тело запроса.
 */
export interface RequestDraft {
  /** Что за товар — своими словами: одежда, косметика, крупногабарит. */
  goods: string;
  /** Объём — те же четыре числа, что считает калькулятор витрины. */
  volume: SellerVolume;
  /** Желаемая дата первой поставки, `YYYY-MM-DD` — как её отдаёт поле даты. */
  date: string;
  /** Город, откуда поедет товар. */
  city: string;
}

export const EMPTY_REQUEST: RequestDraft = {
  goods: "",
  volume: EMPTY_VOLUME,
  date: "",
  city: "",
};

/**
 * Потолок текстовых полей. Не «длиннее не бывает», а граница: заявка едет в
 * письмо складу, и поле, в которое вставили половину прайса, письмо ломает.
 */
export const MAX_TEXT = 120;

/**
 * Чего заявке не хватает. Порядок — как в форме, сверху вниз: человеку
 * называют ближайшее незаполненное поле, а не все сразу.
 */
export type RequestGap = "goods" | "volume" | "date" | "past" | "city";

/**
 * Проверка заявки перед отправкой.
 *
 * Отдаёт список, а не «годится / не годится»: кнопка по нему блокируется, а
 * форма подписывает, что именно осталось. Заблокированная кнопка без причины —
 * тупик, из которого человек уходит со страницы, а не заполняет поле.
 *
 * Дата сравнивается строками: поле даты отдаёт `YYYY-MM-DD`, а такие строки
 * сортируются как сами даты — разбирать их в `Date` незачем.
 */
export function requestGaps(draft: RequestDraft, today: string): RequestGap[] {
  const gaps: RequestGap[] = [];

  if (!draft.goods.trim()) gaps.push("goods");
  if (!isVolumeSet(draft.volume)) gaps.push("volume");

  if (!draft.date) gaps.push("date");
  else if (draft.date < today) gaps.push("past");

  if (!draft.city.trim()) gaps.push("city");

  return gaps;
}

/**
 * Сегодня в том же виде, в каком дату отдаёт поле ввода.
 *
 * Собирается из местных частей даты, а не из `toISOString`: тот считает по
 * Гринвичу, и ночью в Москве вчерашнее число прошло бы как сегодняшнее.
 */
export function todayISO(now: Date = new Date()): string {
  const month = `${now.getMonth() + 1}`.padStart(2, "0");
  const day = `${now.getDate()}`.padStart(2, "0");
  return `${now.getFullYear()}-${month}-${day}`;
}
