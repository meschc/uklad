import type { SiteLang } from "./lang";

/**
 * Даты для витрины: их показывают отзывы, жалобы и свежесть карточки.
 *
 * Отдельным файлом, а не парой строк внутри компонента, по одной причине:
 * формат даты — это то, что должно быть одинаковым на всём сайте, и стоит
 * завести вторую такую функцию рядом, как в одном месте появится «12.09.2026»,
 * а в соседнем «12 сентября». Здесь же лежит и счёт дней, на котором держится
 * правило про жалобы: «склад молчит семнадцатый день» — это не оформление, а
 * содержание.
 */

/** Сутки в миллисекундах. Один на всю витрину: сроки считают трое, и расходиться им нельзя. */
export const DAY_MS = 86_400_000;

/**
 * Момент, относительно которого витрина считает возраст записей.
 *
 * Снимок времени загрузки, а не вызов часов в рендере: рендер обязан быть
 * чистым (иначе React вправе перерисовать компонент и получить другой ответ),
 * а две жалобы, посчитанные по разным вызовам `Date.now()`, на границе полуночи
 * разъедутся на сутки. Страницу читают минуты — снимок даёт ту же точность, что
 * и живые часы, и он же уезжает в пререндер.
 */
export const PAGE_NOW = Date.now();

/**
 * Сколько полных суток прошло с момента `at`.
 *
 * `now` приходит параметром, а не берётся из часов внутри, — ровно по той же
 * причине, что и в `lib/reputation`: функция остаётся чистой и проверяемой без
 * подмены системного времени.
 */
export function daysSince(at: number, now: number): number {
  return Math.max(0, Math.floor((now - at) / DAY_MS));
}

/**
 * Дата одной строкой: «12 сент. 2026 г.» и «12 Sep 2026».
 *
 * Числом месяца, а не «две недели назад»: относительная дата удобна в ленте,
 * которую читают каждый день, а отзыв о складе читают один раз и сравнивают с
 * договором, где стоит число. Год пишется всегда — витрина живёт дольше года,
 * и отзыв без года через сезон становится загадкой.
 */
export function shortDate(lang: SiteLang, at: number): string {
  return new Date(at).toLocaleDateString(lang === "ru" ? "ru-RU" : "en-GB", {
    day: "numeric",
    month: "short",
    year: "numeric",
  });
}
