import { cn } from "@/lib/utils";

/**
 * Надзаголовок — мелкая строчка прописными над крупным заголовком.
 *
 * Название пришло из газетной вёрстки: над заголовком ставили строчку-рубрику,
 * которая говорит, о чём вообще речь, — «Экономика», «Письма читателей».
 * По-английски она называется eyebrow или kicker, по-русски — надзаголовок.
 * Работает она так же и здесь: «Для продавцов», «Тарифы», «Кто работает на
 * складах» — человек понимает раздел раньше, чем дочитает заголовок.
 *
 * Общее у обоих вариантов — прописные с разрядкой, и разрядка обязательна:
 * прописные без неё слипаются в кирпич, потому что рисовались для отдельных
 * букв в начале слова, а не для целого слова.
 *
 * `eyebrow` — обычный: фирменный цвет, тот же кегль, что у подписей вокруг.
 * `eyebrowMono` — технический: моноширинный, чуть крупнее, приглушённый. Стоит
 * над «404» и над экраном ошибки, где строчка означает не рубрику, а код
 * состояния, и должна выглядеть машинной записью, а не разделом сайта.
 *
 * У приложения есть свой такой же модуль,
 * [`@/components/ui/eyebrow`](../../components/ui/eyebrow.ts), но общего кода у
 * них нет намеренно: витрина и приложение — две сборки, и всё, что они делят, —
 * это `cn`.
 *
 *   <p className={eyebrow()}>Тарифы</p>
 *   <p className={eyebrow("mb-3")}>Для продавцов</p>
 *   <p className={eyebrow("mb-7 text-center text-muted-foreground")}>…</p>
 *   <p className={eyebrowMono()}>Ошибка 404</p>
 *
 * Отступ снизу оставлен вызывающему: у надзаголовка в шапке секции он один, у
 * подписи над бегущей строкой — другой, и вариант «mb на выбор» был бы просто
 * переписыванием класса другими буквами.
 *
 * Кегли — ступени шкалы (`fontSize` в tailwind.config.js), а не числа. Раньше
 * здесь стояли `text-[11px]` и `text-[13px]`, и это был как раз тот случай,
 * когда модуль, собранный ради единообразия, сам его и нарушал: 11 против
 * ступени в 12 и 13 против 14 — разница, которую не видно нигде, кроме диффа.
 * Разрядка осталась числом намеренно: значение одно, живёт в одной строке, и
 * ступени у межбуквенного просвета нет — шкалой она станет тогда, когда
 * значений будет больше одного.
 *
 * Цвет перебивается прямо в `extra` — `cn` внутри это `tailwind-merge`, и он
 * убирает `text-primary`, когда следом идёт другой цвет текста. В приложении
 * тот же трюк не прошёл бы: там надзаголовок собран на `cva`, а он классы не
 * сливает, и цвета сложились бы в один класс-список, где победителя выбирает
 * порядок в CSS.
 */
const BASE = "uppercase tracking-[0.14em]";

export function eyebrow(extra?: string): string {
  return cn(BASE, "text-xs font-medium text-primary", extra);
}

export function eyebrowMono(extra?: string): string {
  return cn(BASE, "font-mono text-sm text-muted-foreground", extra);
}
