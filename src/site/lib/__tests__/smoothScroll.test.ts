import { describe, expect, it } from "vitest";
import { ownsWheel } from "../useSmoothScroll";

/**
 * Плавную прокрутку ведёт Lenis, и проверять его самого нам нечем и незачем —
 * поведение видно глазами, а границы вложенных списков и единицы колеса
 * закрыты его собственными тестами. Наше здесь — одно решение: над какими
 * элементами колесо страницы вообще не касается.
 *
 * Оно ломается молча. Ошибись в имени класса — и колесо над картой начнёт
 * заодно уводить страницу: масштаб меняется, карта уезжает из виду, и понять,
 * почему, по коду невозможно. Отсюда и тест на строку.
 */

/** Элемент, от которого проверке нужен только список классов. */
const el = (...classes: string[]) =>
  ({ classList: { contains: (name: string) => classes.includes(name) } }) as unknown as Pick<
    HTMLElement,
    "classList"
  >;

describe("ownsWheel", () => {
  it("отдаёт колесо карте целиком", () => {
    // Колесом над картой меняют масштаб — страница при этом стоять обязана.
    expect(ownsWheel(el("leaflet-container"))).toBe(true);
  });

  it("не трогает соседние элементы карты", () => {
    // Обёртка карты и панель точек прокрутке не мешают: жест над ними — это
    // жест по странице.
    expect(ownsWheel(el("market-map"))).toBe(false);
    expect(ownsWheel(el("leaflet-marker-pane"))).toBe(false);
  });

  it("не путается на элементе без классов", () => {
    expect(ownsWheel(el())).toBe(false);
  });
});
