/**
 * Русское склонение числительных: «1 склад», «2 склада», «12 складов».
 *
 * В приложении такая функция уже есть (`lib/i18n`), но она тянет за собой весь
 * словарь интерфейса: класть словарь редактора планов в бандл лендинга ради
 * шести строк арифметики незачем. У витрины свой перевод (`lib/copy`), и
 * английскую сторону берёт на себя он — `t.plural` вызывает эту функцию только
 * на русском, где у числительных три формы вместо двух.
 */
export function plural(n: number, one: string, few: string, many: string): string {
  const d = n % 10;
  const dd = n % 100;
  if (d === 1 && dd !== 11) return one;
  if (d >= 2 && d <= 4 && (dd < 10 || dd >= 20)) return few;
  return many;
}
