/**
 * Русское склонение числительных: «1 склад», «2 склада», «12 складов».
 *
 * В приложении такая функция уже есть (`lib/i18n`), но она двуязычная и тянет
 * за собой весь словарь интерфейса. Витрина одноязычная, и класть словарь
 * редактора планов в бандл лендинга ради шести строк арифметики незачем.
 */
export function plural(n: number, one: string, few: string, many: string): string {
  const d = n % 10;
  const dd = n % 100;
  if (d === 1 && dd !== 11) return one;
  if (d >= 2 && d <= 4 && (dd < 10 || dd >= 20)) return few;
  return many;
}
