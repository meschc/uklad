import { useEffect } from "react";
import Lenis from "lenis";
import "lenis/dist/lenis.css";

/**
 * Плавная прокрутка витрины — на Lenis.
 *
 * До этого здесь жил свой цикл на полторы сотни строк, и дважды подряд он
 * ломался на одном и том же: на попытке угадать по событию колеса, что за
 * устройство его прислало. Мышь ждёт инерции, а тачпад и Magic Mouse
 * докручиваются системой сами, и вторая инерция поверх системной превращает
 * прокрутку в кисель. Угадывали по величине дельты — и промахнулись: macOS
 * сглаживает колесо обычной мыши так же, как тачпад, дельты приходят
 * дробными, и настоящая мышь оказывалась «тачпадом», то есть плавности не
 * получал никто.
 *
 * Lenis эту задачу решает иначе: он не гадает об устройстве, а сглаживает
 * любой источник, ведя одну общую цель прокрутки, и потому одинаково хорошо
 * ведёт себя и с колесом, и с тачпадом. Заодно из него берутся вещи, которые
 * в своём цикле пришлось бы писать заново: нормализация единиц по браузерам,
 * вложенные полосы прокрутки с их границами, `prefers-reduced-motion`,
 * пересчёт размеров при ресайзе. Locomotive Scroll, с которого начался
 * разговор, с пятой версии — обёртка над тем же Lenis.
 *
 * Что настроено здесь и почему:
 *
 *  - `allowNestedScroll` — колесо над фильтрами, списком у карты и шторкой
 *    крутит их, а не страницу под ними; докрученный до края список отдаёт
 *    колесо странице обратно, как было бы нативно;
 *  - `prevent` — карта Leaflet зумится колесом, и прокрутка её не касается;
 *  - `syncTouch` не включаем: у тач-экранов инерция своя, и подменять её
 *    нашей незачем;
 *  - `anchors` не включаем: у витрины хэш занят маршрутом (`#/market`), и
 *    встроенная обработка якорей приняла бы адрес страницы за имя секции.
 *    Переходы к секциям идут через `scrollToSection` ниже.
 */

/**
 * Экземпляр на всю вкладку — он же владелец прокрутки окна.
 *
 * Модульная переменная, а не контекст: к прокрутке обращаются и обычные
 * функции вне React (`lib/route.ts`), а заводить ради них провайдер и
 * прокидывать хук в каждый вызов — больше кода, чем пользы.
 */
let lenis: Lenis | null = null;

export function useSmoothScroll(): void {
  useEffect(() => {
    const instance = new Lenis({
      // Своего кадрового цикла у нас больше нет — пусть Lenis крутит свой.
      autoRaf: true,
      // Доля оставшегося пути за кадр. Значение по умолчанию — с ним живут и
      // сам lenis.dev, и locomotive: заметно мягче нативной прокрутки, но без
      // ощущения, что страница едет уже без тебя.
      lerp: 0.1,
      allowNestedScroll: true,
      prevent: ownsWheel,
      // Клик по ссылке гасит инерцию: иначе карточка склада открывается, а
      // прокрутка на новой странице ещё доезжает по старой цели.
      stopInertiaOnNavigate: true,
    });
    lenis = instance;

    return () => {
      instance.destroy();
      if (lenis === instance) lenis = null;
    };
  }, []);
}

/**
 * Элементы, которым колесо принадлежит целиком.
 *
 * Вызывается для каждого узла на пути события, поэтому проверка — по самому
 * элементу, без обхода вверх. Карта здесь одна: колесом над ней меняют
 * масштаб, и любое смещение страницы в этот момент — ошибка.
 */
export function ownsWheel(node: Pick<HTMLElement, "classList">): boolean {
  return node.classList.contains("leaflet-container");
}

/**
 * Наверх страницы.
 *
 * По умолчанию мгновенно: это смена раздела, а не прокрутка — человек нажал
 * «Тарифы», и проматывать ему в это время текущую страницу незачем.
 */
export function scrollPageTop(immediate = true): void {
  if (lenis) {
    lenis.scrollTo(0, { immediate, force: true });
    return;
  }
  window.scrollTo({ top: 0, behavior: immediate ? "auto" : "smooth" });
}

/**
 * К секции — с поправкой на липкую шапку.
 *
 * Своей поправки здесь нет намеренно. Высоту шапки знает CSS — это
 * `scroll-padding-top` у `html`, — и её одинаково читают оба пути: и родной
 * `scrollIntoView`, и Lenis, который вдобавок учитывает `scroll-margin-top`
 * самой секции (в правовых документах им отбит запас над заголовком). Пока
 * тут стояло собственное смещение, поправок на одну шапку выходило три, и
 * заголовок раздела уезжал вниз почти на треть экрана.
 *
 * `resize()` перед прокруткой обязателен. Высоту страницы Lenis пересчитывает
 * по `ResizeObserver`, и не сразу, а с задержкой в четверть секунды; цель же
 * он обрезает по той высоте, которую знает сейчас. А зовут нас всегда сразу
 * после того, как содержимое поменялось: переход с правового документа на
 * лендинг, раскрытый раздел, доехавшие картинки. Без пересчёта переход с
 * короткой страницы на длинную упирался в лимит короткой — до нужной секции
 * оставалось четыре тысячи точек.
 */
export function scrollToSection(target: HTMLElement): void {
  if (lenis) {
    lenis.resize();
    lenis.scrollTo(target);
    return;
  }
  target.scrollIntoView({ behavior: "smooth", block: "start" });
}

/**
 * Пауза на время всплывающих слоёв.
 *
 * Фон под модалкой и так не прокручивается — `useOverlay` прячет полосу у
 * `body`. Но цель прокрутки при этом продолжала бы двигаться, и, закрыв слой,
 * человек уезжал бы туда, куда «накрутил» сквозь модалку.
 */
export function setSmoothScrollPaused(paused: boolean): void {
  if (!lenis) return;
  if (paused) lenis.stop();
  else lenis.start();
}
