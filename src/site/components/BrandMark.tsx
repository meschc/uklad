import { useState } from "react";
import { cn } from "@/lib/utils";
import type { MarketplaceRef } from "../data/marketplaces";

/**
 * Знак площадки: логотип из `public/brands` на плитке фирменного цвета.
 *
 * Плитка вернулась, и вот почему. Логотипы площадок нарисованы кем угодно и как
 * угодно: у Wildberries это квадрат 100×100 с собственным скруглением, у Ozon —
 * квадрат 200×200, у Ламоды — квадрат 1000×1000, у Мегамаркета — круг, у Авито
 * — четыре кружка на прозрачном без всякой подложки, и пропорции у всех разные.
 * Положенные «прямо на фон», они и выглядели как склад чужих картинок: одна
 * крупнее соседней, одна круглая, одна вообще без краёв.
 *
 * Теперь форма у знака одна и задаётся здесь: круг, залитый цветом самой марки.
 * Круг, а не скруглённый квадрат, — потому что чужие скругления у всех разные
 * (у Wildberries радиус 20 из 100, у Ozon свой, у Мегамаркета круг), и на общей
 * ленте они спорили друг с другом даже под одинаковой маской. Круг снимает
 * вопрос: собственный угол файла в него не попадает вовсе.
 *
 * Цвет плитки берётся не «фирменный вообще», а ровно тот, которым залита
 * подложка внутри файла (см. `bg` в справочнике) — тогда края логотипа сливаются
 * с плиткой, и на экране остаётся один силуэт, а не картинка в кружке.
 *
 * Инверсии по светлоте больше нет. Ламода — это белые буквы на чёрном, а
 * `invert(1)` превращал её в чёрные буквы на белом: то есть чинил видимость,
 * ломая сам знак. На плитке чёрный работает как есть.
 *
 * `onError` не декоративный: битая картинка в списке площадок читается как
 * «склад с этой площадкой не работает», хотя не загрузился всего лишь файл.
 * Плитка при этом остаётся на месте — меняется только её содержимое.
 */
export function BrandMark({
  brand,
  className,
}: {
  brand: MarketplaceRef;
  className?: string;
}) {
  const [failed, setFailed] = useState(false);
  const showLogo = Boolean(brand.logo) && !failed;

  return (
    <span
      title={brand.title}
      className={cn(
        "flex size-7 shrink-0 items-center justify-center overflow-hidden rounded-full",
        className,
      )}
      style={{ backgroundColor: brand.bg }}
    >
      {showLogo ? (
        <img
          // BASE_URL, а не «/brands/…»: при сборке в подкаталог абсолютный путь
          // от корня ведёт в никуда.
          src={`${import.meta.env.BASE_URL}brands/${brand.logo}`}
          alt=""
          loading="lazy"
          onError={() => setFailed(true)}
          className={cn(
            "size-full object-contain",
            // Знаку без собственной подложки нужно поле: иначе фигуры упрутся
            // в край круга и он их срежет. Знак с подложкой, наоборот, кладётся
            // во всю плитку — его поля уже нарисованы в файле.
            brand.glyphOnly && "scale-[0.68]",
          )}
        />
      ) : (
        <span
          className="text-[10px] font-bold tracking-tight"
          style={{ color: brand.fg ?? "#ffffff" }}
        >
          {brand.short}
        </span>
      )}
    </span>
  );
}
