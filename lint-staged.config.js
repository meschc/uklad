/**
 * Что прогнать по файлам, попавшим в индекс, перед коммитом. Вызывает
 * `.husky/pre-commit`.
 *
 * Порядок внутри списка важен: сначала линтер со своими исправлениями, потом
 * форматтер. Наоборот было бы бессмысленно — `eslint --fix` переставляет код
 * по своим правилам и оставляет после себя строки, которые форматтер всё равно
 * разложит заново.
 *
 * Проверки, которым нужен весь проект целиком — типы, тесты, сборка, — сюда не
 * входят: они не умеют смотреть на отдельный файл и стоят на `pre-push` и в CI.
 * Хук перед коммитом обязан быть быстрым, иначе его начинают обходить.
 */
export default {
  "*.{ts,tsx,js,mjs,cjs}": ["eslint --fix", "prettier --write"],
  // `--ignore-unknown`: под маску попадают и файлы из `.prettierignore`
  // (точки входа HTML, юзермап), и для них форматтер должен промолчать, а не
  // ронять коммит.
  "*.{json,css,md,html}": "prettier --write --ignore-unknown",
};
