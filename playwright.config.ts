import { defineConfig, devices } from "@playwright/test";

/**
 * Сквозные тесты — по собранному сайту, а не по дев-серверу.
 *
 * Причина в том, что ломается обычно именно сборка: витрина и приложение
 * собираются двумя входами (см. `build.rollupOptions.input` в vite.config.ts),
 * и «/app/ открывается» — это утверждение о результате `vite build`, а не о
 * дев-сервере, который отдаёт модули напрямую и про MPA ничего не знает.
 *
 * Порт 4174, а не 5174: на 5174 живёт дев-сервер с реальным планом склада в
 * localStorage. Тесты чистят хранилище своего origin, и совпадение портов
 * означало бы, что прогон тестов стирает рабочие данные.
 */
const PORT = 4174;

export default defineConfig({
  testDir: "./e2e",
  // Полностью параллельно: тесты ничего не делят, кроме статики, а состояние
  // (localStorage) у каждого свой контекст браузера.
  fullyParallel: true,
  forbidOnly: !!process.env.CI,
  retries: process.env.CI ? 1 : 0,
  reporter: process.env.CI ? "line" : [["list"]],

  use: {
    baseURL: `http://localhost:${PORT}`,
    // Трасса только на упавшей повторной попытке: полная запись каждого
    // прогона раздувает артефакты до сотен мегабайт и никто её не открывает.
    trace: "on-first-retry",
    locale: "ru-RU",
    timezoneId: "Europe/Moscow",
  },

  projects: [
    {
      name: "desktop",
      use: { ...devices["Desktop Chrome"], viewport: { width: 1440, height: 900 } },
    },
    {
      // Телефон — не для галочки: витрина, фильтры и правовые документы на
      // узком экране устроены иначе (шторка вместо колонки, нет оглавления).
      name: "mobile",
      use: { ...devices["Pixel 7"] },
    },
    {
      // Узкий телефон, 375 точек. Отдельным проектом, потому что Pixel 7 —
      // это 412, и на нём всё помещалось: ряд «сортировка + переключатель
      // вида» укладывался в ширину, объявление в шапке героя держалось в одну
      // строку, названия складов не раздували колонку. Ровно эти три вещи
      // ломались на 375 — то есть на iPhone SE и 12 mini, а это не экзотика.
      //
      // Ширина задана поверх Pixel 7, а не взята из `devices["iPhone SE"]`:
      // тот тянет WebKit, а нужен здесь не второй движок, а тридцать семь
      // пикселей разницы.
      //
      // Гоняем только габариты: остальные сценарии от ширины не зависят, а
      // полный набор в третий раз — это минута прогона ради повторения того
      // же самого.
      name: "mobile-sm",
      testMatch: /responsive\.spec\.ts/,
      use: { ...devices["Pixel 7"], viewport: { width: 375, height: 667 } },
    },
  ],

  webServer: {
    command: `npm run build && npx vite preview --port ${PORT} --strictPort`,
    url: `http://localhost:${PORT}/`,
    reuseExistingServer: !process.env.CI,
    // Сборка холодная — минуты полторы на слабой машине.
    timeout: 180_000,
    stdout: "pipe",
  },
});
