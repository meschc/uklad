import { defineConfig } from "vitest/config";
import path from "node:path";

/**
 * Тестовый рантайм отдельно от vite.config.ts: приложение и тесты собираются
 * разными конфигами, чтобы в дев-сервер не протекали тестовые настройки.
 *
 * Окружение по умолчанию — node: большинство тестов проверяют чистую логику
 * (`lib/*.ts`) и срезы стора, где ни документа, ни хранилища не нужно, а node
 * стартует заметно быстрее браузерной эмуляции.
 *
 * Компонентные тесты просят jsdom сами — строкой `@vitest-environment jsdom` в
 * шапке файла. Так окружение видно прямо в тесте, а не выводится из имени
 * файла по глобу, спрятанному в конфиге.
 */
export default defineConfig({
  resolve: {
    alias: {
      "@": path.resolve(__dirname, "./src"),
    },
  },
  test: {
    environment: "node",
    include: ["src/**/*.test.ts", "src/**/*.test.tsx"],
    setupFiles: ["./src/test/setup.ts"],
    coverage: {
      provider: "v8",
      // Считаем по всей логике, а не по двум разобранным файлам. Прошлый список
      // из двух путей давал 97 %, но это была цифра про сами тесты, а не про
      // проект: она не могла упасть, потому что в неё попадало только то, что
      // уже закрыто. Честная цифра меньше и от неё есть польза — видно, куда
      // писать следующий тест.
      //
      // Экраны (`.tsx`) в подсчёт не входят намеренно. Их проверяют
      // компонентные и сквозные тесты, а сквозные идут другим прогоном, и в
      // этот отчёт их строки не попадают вовсе. Смешать одно с другим значило
      // бы получить цифру, которая занижена ровно настолько, насколько хорошо
      // работает Playwright. Здесь измеряется логика — и только она.
      include: ["src/lib/**/*.ts", "src/site/lib/**/*.ts", "src/site/data/**/*.ts"],
      exclude: [
        "src/**/__tests__/**",
        // Только объявления типов — исполнять в них нечего.
        "src/lib/types.ts",
        "src/site/data/legal/types.ts",
        // Тексты юридических документов: данные, а не логика.
        "src/site/data/legal/**",
      ],
      reporter: ["text", "json-summary"],
    },
  },
});
